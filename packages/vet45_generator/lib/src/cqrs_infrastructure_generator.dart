import 'codegen_module_config.dart';

abstract final class CqrsInfrastructureGenerator {
  static String generateCommandRegistration(CodegenModuleConfig config) {
    final buffer = StringBuffer()
      ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
      ..writeln('// ignore_for_file: type=lint')
      ..writeln()
      ..writeln("import 'package:get_it/get_it.dart';")
      ..writeln(
        "import 'package:${config.resolvedApplicationPackage}/application.dart';",
      )
      ..writeln("import 'package:vet45_shared_application/application.dart';")
      ..writeln("import 'package:vet45_shared_infrastructure/infrastructure.dart';")
      ..writeln()
      ..writeln("import '${config.resolvedInternalCommandClientImport}';")
      ..writeln("import '${config.resolvedCommandBusExtensionsImport}';")
      ..writeln()
      ..writeln('abstract final class ${config.resolvedRegistrationClass} {')
      ..writeln('  static void registerBusinessHandler<')
      ..writeln('      TCommand extends ICommand<TResult>, TResult, THandler extends Object>({')
      ..writeln('    required GetIt container,')
      ..writeln('    required CommandBus bus,')
      ..writeln('    required THandler Function() factory,')
      ..writeln('    ILogger? logger,')
      ..writeln(
        '    Future<TResult> Function(TCommand command, THandler handler)? invoke,',
      )
      ..writeln('  }) {')
      ..writeln('    if (!container.isRegistered<THandler>()) {')
      ..writeln('      container.registerFactory<THandler>(factory);')
      ..writeln('    }')
      ..writeln()
      ..writeln('    bus.registerBusinessCommand<TCommand, TResult, THandler>(')
      ..writeln('      container: container,')
      ..writeln('      logger: logger,')
      ..writeln('      invoke: invoke ?? (command, handler) => _defaultInvoke(command, handler),')
      ..writeln('    );')
      ..writeln('  }')
      ..writeln()
      ..writeln('  static Future<TResult> _defaultInvoke<')
      ..writeln('      TCommand extends ICommand<TResult>, TResult, THandler>(')
      ..writeln('    TCommand command,')
      ..writeln('    THandler handler,')
      ..writeln('  ) {')
      ..writeln('    if (handler is ICommandHandler<TCommand, TResult>) {')
      ..writeln('      return handler.handle(command);')
      ..writeln('    }')
      ..writeln()
      ..writeln('    throw StateError(')
      ..writeln("      'Handler \${handler.runtimeType} does not implement '")
      ..writeln("      'ICommandHandler<\$TCommand, \$TResult>. Provide a custom invoke callback.',")
      ..writeln('    );')
      ..writeln('  }')
      ..writeln()
      ..writeln('  static void registerInternalHandler<')
      ..writeln('      TCommand extends InternalCommandBase<void>, THandler extends Object>({')
      ..writeln('    required GetIt container,')
      ..writeln('    required CommandBus bus,')
      ..writeln('    required THandler Function() factory,')
      ..writeln('    required Future<void> Function(TCommand command) inner,')
      ..writeln(
        '    required ${config.resolvedInternalCommandClientType} commandClient,',
      )
      ..writeln('    ILogger? logger,')
      ..writeln('  }) {')
      ..writeln('    if (!container.isRegistered<THandler>()) {')
      ..writeln('      container.registerFactory<THandler>(factory);')
      ..writeln('    }')
      ..writeln()
      ..writeln('    bus.registerInternalCommand<TCommand>(')
      ..writeln('      container: container,')
      ..writeln('      logger: logger,')
      ..writeln('      inner: inner,')
      ..writeln('      commandClient: commandClient,')
      ..writeln('    );')
      ..writeln('  }')
      ..writeln()
      ..writeln('  static void registerQueryHandler<')
      ..writeln('      TQuery extends IQuery<TResult>, TResult, THandler extends Object>({')
      ..writeln('    required QueryBus bus,')
      ..writeln('    required THandler Function() factory,')
      ..writeln('    required Future<TResult> Function(TQuery query, THandler handler) invoke,')
      ..writeln('  }) {')
      ..writeln('    final handler = factory();')
      ..writeln('    bus.register<TQuery, TResult>((query) => invoke(query, handler));')
      ..writeln('  }')
      ..writeln('}');

    return buffer.toString();
  }

  static String generateCommandBusExtensions(CodegenModuleConfig config) {
    final pascalCase = config.pascalCase;
    final pipelineClass = config.resolvedCommandPipelineClass;

    final buffer = StringBuffer()
      ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
      ..writeln('// ignore_for_file: type=lint')
      ..writeln()
      ..writeln("import 'package:get_it/get_it.dart';")
      ..writeln(
        "import 'package:${config.resolvedApplicationPackage}/application.dart';",
      )
      ..writeln("import 'package:vet45_shared_application/application.dart';")
      ..writeln("import 'package:vet45_shared_infrastructure/infrastructure.dart';")
      ..writeln()
      ..writeln("import '${config.resolvedInternalCommandClientImport}';")
      ..writeln("import '${config.resolvedCommandPipelineImport}';")
      ..writeln()
      ..writeln('extension ${pascalCase}CommandBusBusinessCommands on CommandBus {')
      ..writeln('  void registerBusinessCommand<')
      ..writeln('      TCommand extends ICommand<TResult>, TResult, THandler extends Object>({')
      ..writeln('    required GetIt container,')
      ..writeln(
        '    required Future<TResult> Function(TCommand command, THandler handler) invoke,',
      )
      ..writeln('    ILogger? logger,')
      ..writeln('  }) {')
      ..writeln('    register<TCommand, TResult>((command) {')
      ..writeln('      final handler = container.get<THandler>();')
      ..writeln('      final pipeline = $pipelineClass.buildBusinessPipeline<')
      ..writeln('          TCommand, TResult, THandler>(')
      ..writeln('        container: container,')
      ..writeln('        handler: handler,')
      ..writeln('        invoke: invoke,')
      ..writeln('        logger: logger,')
      ..writeln('      );')
      ..writeln('      return pipeline(command);')
      ..writeln('    });')
      ..writeln('  }')
      ..writeln('}')
      ..writeln()
      ..writeln('extension ${pascalCase}CommandBusInternalCommands on CommandBus {')
      ..writeln('  void registerInternalCommand<TCommand extends InternalCommandBase<void>>({')
      ..writeln('    required GetIt container,')
      ..writeln('    required Future<void> Function(TCommand command) inner,')
      ..writeln(
        '    required ${config.resolvedInternalCommandClientType} commandClient,',
      )
      ..writeln('    ILogger? logger,')
      ..writeln('  }) {')
      ..writeln('    register<TCommand, void>((command) {')
      ..writeln('      final pipeline = $pipelineClass.buildInternalPipeline<TCommand>(')
      ..writeln('        container: container,')
      ..writeln('        inner: inner,')
      ..writeln('        commandClient: commandClient,')
      ..writeln('        logger: logger,')
      ..writeln('      );')
      ..writeln('      return pipeline(command);')
      ..writeln('    });')
      ..writeln('  }')
      ..writeln('}');

    return buffer.toString();
  }
}
