import 'dart:io';

import 'manifest.dart';
import 'secrets_loader.dart';
import 'supabase_cli.dart';

const _generatedHeader = '# Generated by vet45_env sync — edit config/secrets/ or manifest, then re-run melos run env:sync';

class SyncService {
  SyncService({
    required this.manifest,
    SupabaseCli? supabaseCli,
  }) : _supabaseCli = supabaseCli ?? SupabaseCli(workdir: manifest.rootDir);

  final EnvManifest manifest;
  final SupabaseCli _supabaseCli;

  Future<SyncResult> sync(String environmentId) async {
    final env = manifest.getEnvironment(environmentId);
    final canonical = await _loadCanonical(env);
    _ensureTickSecret(canonical, env);

    final erpValues = _buildErpValues(env, canonical);
    final workerValues = _buildWorkerValues(env, canonical);

    writeDotEnv(env.erp.envFile, erpValues, header: _generatedHeader);
    writeDotEnv(env.worker.envFile, workerValues, header: _generatedHeader);

    return SyncResult(
      environmentId: environmentId,
      erpEnvFile: env.erp.envFile,
      workerEnvFile: env.worker.envFile,
    );
  }

  Future<Map<String, String>> _loadCanonical(EnvironmentDefinition env) async {
    final fromSecrets = loadDotEnv(env.secretsFile);
    if (env.supabaseSource == 'supabase_cli') {
      final status = await _supabaseCli.readStatusEnv();
      final fromCli = _supabaseCli.toCanonical(status);
      return {...fromCli, ...fromSecrets};
    }
    if (env.cliFallback) {
      try {
        final status = await _supabaseCli.readStatusEnv();
        final fromCli = _supabaseCli.toCanonical(status);
        return {...fromCli, ...fromSecrets};
      } on Object {
        return Map<String, String>.from(fromSecrets);
      }
    }
    return Map<String, String>.from(fromSecrets);
  }

  void _ensureTickSecret(Map<String, String> canonical, EnvironmentDefinition env) {
    final existing = canonical['WORKER_TICK_SECRET']?.trim() ?? '';
    if (existing.isNotEmpty) {
      return;
    }
    final generated = generateTickSecret();
    canonical['WORKER_TICK_SECRET'] = generated;
    if (!env.secretsFile.existsSync()) {
      env.secretsFile.parent.createSync(recursive: true);
    }
    final secrets = loadDotEnv(env.secretsFile);
    secrets['WORKER_TICK_SECRET'] = generated;
    writeDotEnv(
      env.secretsFile,
      secrets,
      header: '# Vet45 secrets for ${env.id} — safe to add overrides',
    );
  }

  Map<String, String> _buildErpValues(
    EnvironmentDefinition env,
    Map<String, String> canonical,
  ) {
    final existing = loadDotEnv(env.erp.envFile);
    final supabaseUrl = requireKey(canonical, 'SUPABASE_URL');
    final values = <String, String>{
      'APP_ENV': env.erp.appEnv,
      'SUPABASE_CONNECTION_URL': supabaseUrl,
      'SUPABASE_ANON_KEY': requireKey(canonical, 'SUPABASE_ANON_KEY'),
      'LOG_LEVEL': optionalKey(canonical, 'LOG_LEVEL', 'INFO'),
      'MESSAGING_CLIENT_POLL_ENABLED': optionalKey(
        canonical,
        'MESSAGING_CLIENT_POLL_ENABLED',
        'false',
      ),
    };
    // Preserve deploy-only keys from existing ERP env.
    for (final key in ['APP_STORE_CONNECT_ISSUER_ID', 'APP_STORE_CONNECT_KEY_IDENTIFIER']) {
      final preserved = existing[key]?.trim() ?? '';
      if (preserved.isNotEmpty) {
        values[key] = preserved;
      }
    }
    return values;
  }

  Map<String, String> _buildWorkerValues(
    EnvironmentDefinition env,
    Map<String, String> canonical,
  ) {
    return {
      'SUPABASE_URL': requireKey(canonical, 'SUPABASE_URL'),
      'SUPABASE_SERVICE_ROLE_KEY': requireKey(canonical, 'SUPABASE_SERVICE_ROLE_KEY'),
      'WORKER_TICK_SECRET': requireKey(canonical, 'WORKER_TICK_SECRET'),
      'WORKER_TENANT_BATCH_SIZE': optionalKey(canonical, 'WORKER_TENANT_BATCH_SIZE', '20'),
      'WORKER_MODULE_BATCH_SIZE': optionalKey(canonical, 'WORKER_MODULE_BATCH_SIZE', '10'),
      'WORKER_MAX_ROUNDS_PER_TICK': optionalKey(canonical, 'WORKER_MAX_ROUNDS_PER_TICK', '5'),
      'WORKER_TICK_ACTIVE_SECONDS': optionalKey(canonical, 'WORKER_TICK_ACTIVE_SECONDS', '3'),
      'WORKER_TICK_IDLE_SECONDS': optionalKey(canonical, 'WORKER_TICK_IDLE_SECONDS', '15'),
      'WORKER_TICK_MAX_IDLE_SECONDS': optionalKey(canonical, 'WORKER_TICK_MAX_IDLE_SECONDS', '30'),
      'PORT': optionalKey(canonical, 'PORT', '8080'),
      'WORKER_LOG_LEVEL': optionalKey(canonical, 'WORKER_LOG_LEVEL', 'INFO'),
    };
  }
}

class SyncResult {
  SyncResult({
    required this.environmentId,
    required this.erpEnvFile,
    required this.workerEnvFile,
  });

  final String environmentId;
  final File erpEnvFile;
  final File workerEnvFile;
}
