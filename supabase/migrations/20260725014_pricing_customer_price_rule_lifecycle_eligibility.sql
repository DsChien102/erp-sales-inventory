create or replace function pricing.resolve_applicable_customer_price_rule(
  p_tenant_id uuid,
  p_customer_id uuid,
  p_product_id uuid,
  p_product_unit_id uuid,
  p_business_date date
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_actor_id uuid := auth.uid();
  v_count integer := 0;
  v_rule pricing.customer_price_rules%rowtype;
begin
  if v_actor_id is null
    or not iam.has_permission(
      p_tenant_id,
      'pricing.customer_price_rule.view'
    ) then
    perform pricing._raise_pricing_error(
      'NO_PERMISSION',
      'Permission denied.',
      jsonb_build_object('permission', 'pricing.customer_price_rule.view')
    );
  end if;

  if p_customer_id is null
    or p_product_id is null
    or p_product_unit_id is null
    or p_business_date is null then
    perform pricing._raise_pricing_error(
      'VALIDATION_ERROR',
      'Invalid resolve applicable customer price rule payload.'
    );
  end if;

  select count(*)::integer into v_count
  from pricing.customer_price_rules r
  where r.tenant_id = p_tenant_id
    and r.customer_id = p_customer_id
    and r.product_id = p_product_id
    and r.product_unit_id = p_product_unit_id
    and r.status = 'active'
    and r.deleted_at is null
    and r.effective_from <= p_business_date
    and p_business_date <= coalesce(r.effective_to, 'infinity'::date)
    and jsonb_array_length(coalesce(r.blocking_codes, '[]'::jsonb)) = 0
    and coalesce(r.review_status, 'clear') not in ('blocked', 'needs_review');

  if v_count > 1 then
    raise log
      'pricing.resolve_applicable_customer_price_rule integrity: % applicable rows tenant=% customer=% product=% unit=% date=%',
      v_count, p_tenant_id, p_customer_id, p_product_id, p_product_unit_id, p_business_date;
    perform pricing._raise_pricing_error(
      'SYSTEM_ERROR',
      'Multiple applicable customer price rules found for the same key.'
    );
  end if;

  if v_count = 0 then
    return jsonb_build_object('rule', null);
  end if;

  select r.* into v_rule
  from pricing.customer_price_rules r
  where r.tenant_id = p_tenant_id
    and r.customer_id = p_customer_id
    and r.product_id = p_product_id
    and r.product_unit_id = p_product_unit_id
    and r.status = 'active'
    and r.deleted_at is null
    and r.effective_from <= p_business_date
    and p_business_date <= coalesce(r.effective_to, 'infinity'::date)
    and jsonb_array_length(coalesce(r.blocking_codes, '[]'::jsonb)) = 0
    and coalesce(r.review_status, 'clear') not in ('blocked', 'needs_review')
  limit 1;

  return jsonb_build_object(
    'rule', jsonb_build_object(
      'rule_id', v_rule.id,
      'price', jsonb_build_object(
        'amount_minor', v_rule.rule_price_minor,
        'currency_code', v_rule.currency_code
      ),
      'effective_period', jsonb_build_object(
        'effective_from', v_rule.effective_from,
        'effective_to', v_rule.effective_to
      ),
      'source_type', v_rule.source_type,
      'version', v_rule.version
    )
  );
end;
$$;

