create or replace function pricing.delete_customer_price_rule(
  p_tenant_id uuid,
  p_rule_id uuid,
  p_expected_version integer
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor_id uuid := auth.uid();
  v_rule pricing.customer_price_rules%rowtype;
  v_old_value jsonb;
  v_payload jsonb;
begin
  if v_actor_id is null
    or not iam.has_permission(
      p_tenant_id,
      'pricing.customer_price_rule.delete'
    ) then
    perform pricing._raise_pricing_error(
      'NO_PERMISSION',
      'Permission denied.',
      jsonb_build_object('permission', 'pricing.customer_price_rule.delete')
    );
  end if;

  if p_rule_id is null
    or p_expected_version is null
    or p_expected_version <= 0 then
    perform pricing._raise_pricing_error(
      'VALIDATION_ERROR',
      'Invalid customer price rule delete payload.'
    );
  end if;

  select r.* into v_rule
  from pricing.customer_price_rules r
  where r.tenant_id = p_tenant_id
    and r.id = p_rule_id
  for update;

  if not found then
    perform pricing._raise_pricing_error(
      'NOT_FOUND',
      'Customer price rule was not found.'
    );
  end if;

  if v_rule.status = 'deleted' then
    v_payload := (pricing._customer_price_rule_result(
      v_rule.id,
      iam.has_permission(
        p_tenant_id,
        'pricing.customer_price_rule.override_floor_price'
      )
    ) -> 'rule') || jsonb_build_object(
      'deleted_at', v_rule.deleted_at,
      'derived_status', 'deleted',
      'available_actions', '[]'::jsonb
    );
    return v_payload;
  end if;

  if v_rule.version <> p_expected_version then
    perform pricing._raise_pricing_error(
      'STATE_CHANGED',
      'Customer price rule version changed.',
      jsonb_build_object(
        'expectedVersion', p_expected_version,
        'currentVersion', v_rule.version
      )
    );
  end if;

  if v_rule.status = 'disabled' then
    perform pricing._raise_pricing_error(
      'INVALID_STATUS',
      'Customer price rule cannot be deleted in its current status.',
      jsonb_build_object('status', v_rule.status)
    );
  end if;

  if v_rule.status not in ('active', 'needs_review') then
    perform pricing._raise_pricing_error(
      'INVALID_STATUS',
      'Customer price rule cannot be deleted in its current status.',
      jsonb_build_object('status', v_rule.status)
    );
  end if;

  v_old_value := jsonb_build_object(
    'status', v_rule.status,
    'version', v_rule.version
  );

  update pricing.customer_price_rules
  set status = 'deleted',
      deleted_at = statement_timestamp(),
      updated_by = v_actor_id,
      updated_at = statement_timestamp(),
      version = v_rule.version + 1
  where id = v_rule.id
  returning * into v_rule;

  insert into pricing.customer_price_rule_activities (
    tenant_id,
    customer_price_rule_id,
    activity_type,
    old_value,
    new_value,
    created_by
  ) values (
    p_tenant_id,
    v_rule.id,
    'deleted',
    v_old_value,
    jsonb_build_object(
      'status', v_rule.status,
      'version', v_rule.version,
      'deleted_at', v_rule.deleted_at
    ),
    v_actor_id
  );

  return (pricing._customer_price_rule_result(
    v_rule.id,
    iam.has_permission(
      p_tenant_id,
      'pricing.customer_price_rule.override_floor_price'
    )
  ) -> 'rule') || jsonb_build_object(
    'deleted_at', v_rule.deleted_at,
    'derived_status', 'deleted',
    'available_actions', '[]'::jsonb
  );
end;
$$;

