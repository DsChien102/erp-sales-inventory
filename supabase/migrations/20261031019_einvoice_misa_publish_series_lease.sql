create or replace function einvoice.reschedule_internal_command(
  p_tenant_id uuid,
  p_command_id uuid,
  p_claim_token uuid,
  p_delay_seconds integer
) returns void
language plpgsql security definer set search_path = einvoice, platform, pg_temp as $$
declare
  v_cmd einvoice.internal_commands%rowtype;
  v_delay interval;
begin
  select ic.*
  into v_cmd
  from einvoice.internal_commands ic
  where ic.id = p_command_id
    and ic.tenant_id = p_tenant_id
    and ic.claim_token = p_claim_token
    and ic.processed_at is null
    and ic.failed_at is null
  for update;

  if not found then
    raise exception 'NOT_FOUND: internal command or claim token mismatch';
  end if;

  v_delay := make_interval(secs => greatest(p_delay_seconds, 1));

  update einvoice.internal_commands
  set enqueued_at = now() + v_delay,
      claimed_at = null,
      claim_token = null,
      updated_at = now()
  where id = p_command_id;
end;
$$;

