security definer
set search_path = einvoice, public
as $$
declare
  v_case einvoice.invoice_reconciliation_cases%rowtype;
  v_delivery einvoice.invoice_deliveries%rowtype;
  v_connection einvoice.provider_connections%rowtype;
  v_supports boolean;
begin
  if coalesce(
    nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role',
    nullif(current_setting('request.jwt.claim.role', true), '')
  ) is distinct from 'service_role' then
    raise exception 'NO_PERMISSION: service role required';
  end if;

  if p_check_sequence is null or p_check_sequence < 1 then
    return;
  end if;

  select irc.*
  into v_case
  from einvoice.invoice_reconciliation_cases irc
  where irc.tenant_id = p_tenant_id
    and irc.id = p_reconciliation_case_id
  for update;

  if not found then
    return;
  end if;

  if v_case.target_type is distinct from 'INVOICE_DELIVERY' then
    return;
  end if;

  -- Stale / already terminal: worker acknowledges without work.
  if v_case.status is distinct from 'PENDING' then
    return;
  end if;

  if v_case.check_count + 1 is distinct from p_check_sequence then
    return;
  end if;

  select d.*
  into v_delivery
  from einvoice.invoice_deliveries d
  where d.tenant_id = p_tenant_id
    and d.id = v_case.target_id
  for update;

  if not found then
    return;
  end if;

  select pc.*
  into v_connection
  from einvoice.provider_connections pc
  where pc.tenant_id = p_tenant_id
    and pc.id = v_case.provider_connection_id;

  v_supports := coalesce(
    (v_connection.capabilities_snapshot ->> 'supports_delivery_result_observation')::boolean,
    false
  );

  return query select
    p_tenant_id,
    v_case.id,
    v_delivery.id,
    v_case.provider_connection_id,
    v_supports,
    p_check_sequence,
    v_case.version,
    nullif(btrim(coalesce(v_delivery.provider_delivery_reference, '')), '');
end;
$$;

