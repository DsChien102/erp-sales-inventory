drop function if exists einvoice.record_delivery_reconciliation_check(uuid, uuid, bigint, integer, text, text, text, text);
create or replace function einvoice.record_delivery_reconciliation_check(
  p_tenant_id uuid,
  p_reconciliation_case_id uuid,
  p_expected_case_version bigint,
  p_check_sequence integer,
  p_observation_kind text,
  p_provider_reference text,
  p_safe_code text
) returns table(
  case_status text,
  delivery_status text,
  next_check_at timestamptz,
  has_secondary_attention boolean
)
language plpgsql
security definer
set search_path = einvoice, public
as $$
declare
  v_case einvoice.invoice_reconciliation_cases%rowtype;
  v_delivery einvoice.invoice_deliveries%rowtype;
  v_invoice einvoice.electronic_invoices%rowtype;
  v_kind text := upper(btrim(coalesce(p_observation_kind, '')));
  v_safe_code text := nullif(btrim(coalesce(p_safe_code, '')), '');
  v_safe_message text;
  v_statuses text[];
  v_projection record;
  v_next_check timestamptz;
  v_next_sequence integer;
  v_cmd_id uuid;
  v_emit_attention boolean := false;
begin
  if coalesce(
    nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role',
    nullif(current_setting('request.jwt.claim.role', true), '')
  ) is distinct from 'service_role' then
    raise exception 'NO_PERMISSION: service role required';
  end if;

  if v_kind not in ('SUCCESS', 'DEFINITE_FAILURE', 'UNDETERMINED', 'UNSUPPORTED') then
    raise exception 'VALIDATION_ERROR: unknown observation kind %', p_observation_kind;
  end if;

  select irc.*
  into v_case
  from einvoice.invoice_reconciliation_cases irc
  where irc.tenant_id = p_tenant_id
    and irc.id = p_reconciliation_case_id
  for update;

  if not found then
    raise exception 'NOT_FOUND: reconciliation case';
  end if;

  if v_case.target_type is distinct from 'INVOICE_DELIVERY' then
    raise exception 'VALIDATION_ERROR: case is not an INVOICE_DELIVERY case';
  end if;

  if v_case.version is distinct from p_expected_case_version then
    if v_case.status in ('RESOLVED', 'UNRESOLVED') then
      select d.*
      into v_delivery
      from einvoice.invoice_deliveries d
      where d.tenant_id = p_tenant_id
        and d.id = v_case.target_id;

      select coalesce(array_agg(d.status order by d.delivery_no), '{}'::text[])
      into v_statuses
      from einvoice.invoice_deliveries d
      where d.tenant_id = p_tenant_id
        and d.electronic_invoice_id = v_delivery.electronic_invoice_id;

      select p.*
      into v_projection
      from einvoice._delivery_display_projection(v_statuses) p;

      return query select
        v_case.status::text,
        v_delivery.status::text,
        v_case.next_check_at,
        v_projection.has_secondary_attention;
      return;
    end if;
    raise exception 'STATE_CHANGED: expected version mismatch';
  end if;

  select d.*
  into v_delivery
  from einvoice.invoice_deliveries d
  where d.tenant_id = p_tenant_id
    and d.id = v_case.target_id
  for update;

  if not found then
    raise exception 'NOT_FOUND: invoice delivery';
  end if;

  select ei.*
  into v_invoice
  from einvoice.electronic_invoices ei
  where ei.tenant_id = p_tenant_id
    and ei.id = v_delivery.electronic_invoice_id;

  -- Never reverse a prior success on this delivery.
  if v_delivery.status = 'SUCCEEDED' then
    if v_case.status in ('PENDING', 'UNRESOLVED')
       and v_kind in ('SUCCESS', 'DEFINITE_FAILURE', 'UNSUPPORTED') then
      update einvoice.invoice_reconciliation_cases
      set status = 'RESOLVED',
          check_count = greatest(check_count, p_check_sequence),
          next_check_at = null,
          last_checked_at = now(),
          resolved_at = coalesce(resolved_at, now()),
          resolution_code = coalesce(resolution_code, 'ALREADY_SUCCEEDED'),
          version = version + 1
      where id = p_reconciliation_case_id
      returning * into v_case;
    end if;

    select coalesce(array_agg(d.status order by d.delivery_no), '{}'::text[])
    into v_statuses
    from einvoice.invoice_deliveries d
    where d.tenant_id = p_tenant_id
      and d.electronic_invoice_id = v_delivery.electronic_invoice_id;

    select p.*
    into v_projection
    from einvoice._delivery_display_projection(v_statuses) p;

    return query select
      v_case.status::text,
      v_delivery.status::text,
      v_case.next_check_at,
      v_projection.has_secondary_attention;
    return;
  end if;

  if v_case.status = 'RESOLVED' then
    select coalesce(array_agg(d.status order by d.delivery_no), '{}'::text[])
    into v_statuses
    from einvoice.invoice_deliveries d
    where d.tenant_id = p_tenant_id
      and d.electronic_invoice_id = v_delivery.electronic_invoice_id;

    select p.*
    into v_projection
    from einvoice._delivery_display_projection(v_statuses) p;

    return query select
      v_case.status::text,
      v_delivery.status::text,
      v_case.next_check_at,
      v_projection.has_secondary_attention;
    return;
  end if;

  -- Late authenticated terminal evidence may amend PENDING or UNRESOLVED → RESOLVED.
  if v_case.status not in ('PENDING', 'UNRESOLVED') then
    raise exception 'INVALID_STATUS: case is %', v_case.status;
  end if;

  v_safe_message := case coalesce(v_safe_code, '')
    when 'DELIVERY_RESULT_OBSERVATION_UNSUPPORTED' then
      'Delivery result observation is not supported by the provider'
    when 'DELIVERY_RECONCILIATION_WORKER_EXHAUSTED' then
      'Worker exhausted delivery reconciliation before a conclusive check'
    when 'PROVIDER_DELIVERY_PENDING' then
      'Delivery result is still undetermined'
    when 'PROVIDER_DELIVERY_REJECTED' then
      'Provider rejected the delivery'
    when 'PROVIDER_TIMEOUT' then
      'Provider response timed out'
    when 'PROVIDER_TRANSPORT_FAILURE' then
      'Provider transport failure'
    when '' then null
    else 'Delivery reconciliation recorded with allow-listed failure code'
  end;

  if v_kind = 'UNSUPPORTED' then
    update einvoice.invoice_reconciliation_cases
    set status = 'UNRESOLVED',
        check_count = p_check_sequence,
        next_check_at = null,
        last_checked_at = now(),
        last_error_code = coalesce(v_safe_code, 'DELIVERY_RESULT_OBSERVATION_UNSUPPORTED'),
        version = version + 1
    where id = p_reconciliation_case_id
    returning * into v_case;
    v_emit_attention := true;

  elsif v_kind = 'SUCCESS' then
    update einvoice.invoice_deliveries
    set status = 'SUCCEEDED',
        provider_delivery_reference = coalesce(
          nullif(btrim(coalesce(p_provider_reference, '')), ''),
          provider_delivery_reference
        ),
        failure_code = null,
        failure_message = null,
        failure_source = null,
        completed_at = coalesce(completed_at, now()),
        version = version + 1
    where id = v_delivery.id
    returning * into v_delivery;

    update einvoice.invoice_reconciliation_cases
    set status = 'RESOLVED',
        check_count = greatest(check_count, p_check_sequence),
        next_check_at = null,
        last_checked_at = now(),
        resolved_at = coalesce(resolved_at, now()),
        resolution_code = 'SUCCESS',
        last_error_code = null,
        version = version + 1
    where id = p_reconciliation_case_id
    returning * into v_case;

  elsif v_kind = 'DEFINITE_FAILURE' then
    update einvoice.invoice_deliveries
    set status = 'FAILED',
        failure_code = v_safe_code,
        failure_message = v_safe_message,
        failure_source = 'PROVIDER',
        completed_at = coalesce(completed_at, now()),
        version = version + 1
    where id = v_delivery.id
    returning * into v_delivery;

    update einvoice.invoice_reconciliation_cases
    set status = 'RESOLVED',
        check_count = greatest(check_count, p_check_sequence),
        next_check_at = null,
        last_checked_at = now(),
        resolved_at = coalesce(resolved_at, now()),
        resolution_code = coalesce(v_safe_code, 'DEFINITE_FAILURE'),
        last_error_code = v_safe_code,
        version = version + 1
    where id = p_reconciliation_case_id
    returning * into v_case;

  elsif v_kind = 'UNDETERMINED' then
    if p_check_sequence >= 5 then
      update einvoice.invoice_reconciliation_cases
      set status = 'UNRESOLVED',
          check_count = p_check_sequence,
          next_check_at = null,
          last_checked_at = now(),
          last_error_code = coalesce(v_safe_code, 'PROVIDER_DELIVERY_PENDING'),
          version = version + 1
      where id = p_reconciliation_case_id
      returning * into v_case;
      v_emit_attention := true;
    else
      v_next_sequence := p_check_sequence + 1;
      v_next_check := case p_check_sequence
        when 1 then now() + interval '2 minutes'
        when 2 then now() + interval '10 minutes'
        when 3 then now() + interval '30 minutes'
        when 4 then now() + interval '2 hours'
        else now() + interval '2 hours'
      end;

      update einvoice.invoice_reconciliation_cases
      set status = 'PENDING',
          check_count = p_check_sequence,
          next_check_at = v_next_check,
          last_checked_at = now(),
          last_error_code = coalesce(v_safe_code, 'PROVIDER_DELIVERY_PENDING'),
          version = version + 1
      where id = p_reconciliation_case_id
      returning * into v_case;

      v_cmd_id := einvoice._delivery_reconciliation_command_id(
        p_reconciliation_case_id,
        v_next_sequence
      );
      insert into einvoice.internal_commands (
        id,
        tenant_id,
        command_type,
        payload,
        source_event_id,
        enqueued_at,
        created_at
      ) values (
        v_cmd_id,
        p_tenant_id,
        'einvoice.reconcile_invoice_delivery',
        jsonb_build_object(
          'tenantId', p_tenant_id,
          'reconciliationCaseId', p_reconciliation_case_id,
          'checkSequence', v_next_sequence
        ),
        v_cmd_id,
        v_next_check,
        now()
      )
      on conflict (id) do nothing;
    end if;
  end if;

  if v_emit_attention then
    perform einvoice.enqueue_outbox_message(
      p_tenant_id,
      'einvoice.delivery.attention_required',
      jsonb_build_object(
        'tenant_id', p_tenant_id,
        'sales_order_id', v_invoice.sales_order_id,
        'electronic_invoice_id', v_invoice.id,
        'delivery_id', v_delivery.id,
        'reconciliation_case_id', v_case.id,
        'safe_error_code', coalesce(
          v_case.last_error_code,
          'DELIVERY_RESULT_OBSERVATION_UNSUPPORTED'
        )
      )
    );
  end if;

  select d.*
  into v_delivery
  from einvoice.invoice_deliveries d
  where d.id = v_delivery.id;

  select coalesce(array_agg(d.status order by d.delivery_no), '{}'::text[])
  into v_statuses
  from einvoice.invoice_deliveries d
  where d.tenant_id = p_tenant_id
    and d.electronic_invoice_id = v_delivery.electronic_invoice_id;

  select p.*
  into v_projection
  from einvoice._delivery_display_projection(v_statuses) p;

  return query select
    v_case.status::text,
    v_delivery.status::text,
    v_case.next_check_at,
    v_projection.has_secondary_attention;
end;
$$;

