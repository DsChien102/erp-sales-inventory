      p.id,
      p.name,
      p.trade_name,
      p.sku,
      p.barcode,
      p.search_document,
      (
        select coalesce(i.file_url, i.storage_key)
        from catalog.product_images i
        where i.product_id = p.id
          and i.tenant_id = p_tenant_id
        order by i.is_primary desc, i.sort_order asc, i.created_at asc
        limit 1
      ) as primary_image_url,
