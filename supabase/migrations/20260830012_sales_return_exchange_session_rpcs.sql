         or v_src_product_unit_id is distinct from (v_line ->> 'product_unit_id')::uuid) then
      raise exception using message = jsonb_build_object(
        'code', 'RETURN_EXCHANGE_BLOCKED',
        'message', 'Hàng trả phải cùng sản phẩm và đơn vị với dòng gốc.'
      )::text;
    end if;
    if v_role = 'exchange' then
      v_unit_snapshot := coalesce(v_unit_snapshot, '{}'::jsonb) || jsonb_build_object(
        'conversionRateToBase',
        sales._product_unit_conversion_rate(
          update_return_exchange.tenant_id,
          (v_line ->> 'product_id')::uuid,
          (v_line ->> 'product_unit_id')::uuid
        )
      );
    end if;
    v_base_qty := sales._base_quantity_micros(
      v_qty, (v_unit_snapshot ->> 'conversionRateToBase')::numeric
    );

    insert into sales.return_exchange_lines (
      id, tenant_id, return_exchange_order_id, source_sales_order_id, line_sequence,
      line_role, original_sales_order_line_id, source_exchange_line_id, product_id, product_unit_id,
      quantity_micros, base_quantity_micros, unit_value_minor,
      return_reason_code, return_condition_code, product_snapshot, product_unit_snapshot
    ) values (
      v_line_id, update_return_exchange.tenant_id, v_session.id, v_order.id, v_line_seq,
      v_role, v_orig, v_src_exchange, (v_line ->> 'product_id')::uuid, (v_line ->> 'product_unit_id')::uuid,
      v_qty, v_base_qty, v_unit_price_minor,
      case when v_role = 'returned' then upper(nullif(btrim(v_line ->> 'reason_code'), '')) else null end,
      case when v_role = 'returned' then upper(nullif(btrim(v_line ->> 'condition_code'), '')) else null end,
      coalesce(v_product_snapshot, '{}'::jsonb),
      coalesce(v_unit_snapshot, '{}'::jsonb)
    );
  end loop;

  update sales.return_exchange_orders
  set version = version + 1,
      reason = nullif(btrim(update_return_exchange.reason), ''),
      correlation_id = update_return_exchange.correlation_id,
      updated_at = now()
  where id = v_session.id
    and tenant_id = update_return_exchange.tenant_id
  returning * into v_session;

  v_result := sales._get_return_exchange_context(
    update_return_exchange.tenant_id, update_return_exchange.actor_id, v_session.id
  ) -> 'draft';
  perform sales._complete_sales_idempotency(
    tenant_id, 'update_return_exchange', trim(idempotency_key),
    'succeeded', v_result);
  return v_result;
end;
$$;

create or replace function sales.cancel_return_exchange(
  command_id text,
  tenant_id uuid,
  actor_id uuid,
  return_exchange_id uuid,
  idempotency_key text,
  payload_hash text default null,
  correlation_id text default null,
  causation_id text default null,
  expected_version integer default null
) returns jsonb
language plpgsql
security definer
set search_path = sales, iam, public, pg_temp
as $$
#variable_conflict use_column
declare
  v_session sales.return_exchange_orders%rowtype;
  v_order sales.sales_orders%rowtype;
  v_idem jsonb;
  v_correlation uuid;
  v_result jsonb;
  v_hash text := coalesce(nullif(trim(coalesce(payload_hash, '')), ''), '');
begin
  if auth.uid() is distinct from actor_id
    or iam.has_permission(tenant_id, 'sales.return_exchange.cancel') is not true then
    raise exception using message = jsonb_build_object(
      'code', 'PERMISSION_DENIED', 'message', 'Permission denied.'
    )::text;
  end if;

  begin
    v_correlation := nullif(trim(coalesce(correlation_id, '')), '')::uuid;
  exception when others then
    v_correlation := null;
  end;
  if v_correlation is null then
    begin
      v_correlation := nullif(trim(coalesce(command_id, '')), '')::uuid;
    exception when others then
      v_correlation := gen_random_uuid();
    end;
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(tenant_id::text || ':cancel_return_exchange:' || idempotency_key, 0)
  );

  v_idem := sales._begin_sales_idempotency(
    tenant_id, 'cancel_return_exchange', idempotency_key,
    coalesce(nullif(v_hash, ''), 'cancel'));
  if v_idem ->> 'decision' = 'replay' then
    return coalesce(v_idem -> 'result_snapshot', '{}'::jsonb);
  end if;
  if v_idem ->> 'decision' = 'in_progress' then
    raise exception using message = jsonb_build_object(
      'code', 'IDEMPOTENCY_CONFLICT', 'message', 'Return/exchange cancel is already in progress.'
    )::text;
  end if;

  select * into v_session
  from sales.return_exchange_orders
  where return_exchange_orders.id = cancel_return_exchange.return_exchange_id
    and return_exchange_orders.tenant_id = cancel_return_exchange.tenant_id
  for update;
  if not found then
    raise exception using message = jsonb_build_object(
      'code', 'NOT_FOUND', 'message', 'Return/exchange session not found.'
    )::text;
  end if;

  if v_session.status = 'cancelled' then
    v_result := jsonb_build_object(
      'returnExchangeId', v_session.id,
      'salesOrderId', v_session.sales_order_id,
      'version', v_session.version,
      'status', 'cancelled'
    );
    perform sales._complete_sales_idempotency(
      tenant_id, 'cancel_return_exchange', trim(idempotency_key),
      'succeeded', v_result);
    return v_result;
  end if;

  if v_session.status is distinct from 'draft' then
    raise exception using message = jsonb_build_object(
      'code', 'RETURN_EXCHANGE_BLOCKED',
      'message', 'Only draft return/exchange sessions may be cancelled.'
    )::text;
  end if;

  if expected_version is not null and v_session.version is distinct from expected_version then
    raise exception using message = jsonb_build_object(
      'code', 'STALE_VERSION', 'message', 'Return/exchange version is stale.'
    )::text;
  end if;

  select * into v_order
  from sales.sales_orders
  where sales_orders.id = v_session.sales_order_id
    and sales_orders.tenant_id = cancel_return_exchange.tenant_id;

  perform sales._assert_sales_actor(
    tenant_id, actor_id, v_order.store_id, 'sales.return_exchange.cancel'
  );

  -- Model B handoff deferred: reservation releases are not dispatched to Inventory here.
  update sales.return_exchange_orders
  set status = 'cancelled',
      version = version + 1,
      updated_at = now()
  where id = v_session.id
    and tenant_id = cancel_return_exchange.tenant_id
  returning * into v_session;

  v_result := jsonb_build_object(
    'returnExchangeId', v_session.id,
    'salesOrderId', v_session.sales_order_id,
    'version', v_session.version,
    'status', 'cancelled'
  );
  perform sales._complete_sales_idempotency(
    tenant_id, 'cancel_return_exchange', trim(idempotency_key),
    'succeeded', v_result);
  return v_result;
end;
$$;

