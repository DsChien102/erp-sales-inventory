    )::text;
  end if;

  if not iam.can_access_store(precheck_return_exchange.tenant_id, v_order.store_id, precheck_return_exchange.actor_id) then
    raise exception using message = jsonb_build_object(
      'code', 'DATA_SCOPE_DENIED', 'message', 'Store scope denied.'
    )::text;
  end if;

  if v_order.lifecycle_status is distinct from 'completed' then
    v_blockers := v_blockers || jsonb_build_array(jsonb_build_object(
      'code', 'RETURN_EXCHANGE_BLOCKED',
      'message', 'Only completed sales orders may start a return/exchange.',
      'field', 'lifecycleStatus'
    ));
  end if;

  if exists (
    select 1 from sales.sales_order_cancellations c
    where c.tenant_id = precheck_return_exchange.tenant_id
      and c.sales_order_id = precheck_return_exchange.sales_order_id
      and c.status in ('requested', 'validating', 'confirmed', 'processing', 'completed')
  ) then
    v_blockers := v_blockers || jsonb_build_array(jsonb_build_object(
      'code', 'COMPETING_CANCELLATION',
      'message', 'A competing cancellation blocks return/exchange entry.'
    ));
  end if;

  select coalesce(sum(l.quantity_micros), 0) into v_sold_micros
  from sales.sales_order_lines l
  where l.tenant_id = precheck_return_exchange.tenant_id
    and l.sales_order_id = v_order.id;

  -- B2a: chi tru cac dong tra co nguon GOC khoi luong ban goc; dong tra nguon
  -- exchange duoc tinh rieng trong v_exchange_returnable_micros (tranh dem 2 lan).
  select coalesce(sum(rl.quantity_micros), 0) into v_reserved_micros
  from sales.return_exchange_lines rl
  join sales.return_exchange_orders r
    on r.id = rl.return_exchange_order_id
   and r.tenant_id = rl.tenant_id
  where r.tenant_id = precheck_return_exchange.tenant_id
    and r.sales_order_id = v_order.id
    and r.status in ('confirmed', 'processing', 'completed')
    and rl.line_role = 'returned'
    and rl.original_sales_order_line_id is not null;

  -- ADR-9: confirmed exchange lines add returnable capacity.
  select coalesce(sum(greatest(
    xl.quantity_micros - coalesce((
      select sum(rl.quantity_micros)
      from sales.return_exchange_lines rl
      join sales.return_exchange_orders r
        on r.id = rl.return_exchange_order_id and r.tenant_id = rl.tenant_id
      where r.tenant_id = precheck_return_exchange.tenant_id
        and r.sales_order_id = v_order.id
        and r.status in ('confirmed', 'processing', 'completed')
        and rl.line_role = 'returned'
        and rl.source_exchange_line_id = xl.id
    ), 0), 0)), 0)
  into v_exchange_returnable_micros
  from sales.return_exchange_lines xl
  join sales.return_exchange_orders xr
    on xr.id = xl.return_exchange_order_id and xr.tenant_id = xl.tenant_id
  where xl.tenant_id = precheck_return_exchange.tenant_id
    and xr.sales_order_id = v_order.id
    and xl.line_role = 'exchange'
    and xr.status in ('confirmed', 'processing', 'completed');

  if greatest(v_sold_micros - v_reserved_micros, 0) + v_exchange_returnable_micros <= 0 then
    v_blockers := v_blockers || jsonb_build_array(jsonb_build_object(
      'code', 'RETURN_EXCHANGE_BLOCKED',
      'message', 'No returnable quantity remains on this sales order.'
    ));
  end if;

  return jsonb_build_object(
    'allowed', jsonb_array_length(v_blockers) = 0,
    'sourceVersion', v_order.version,
    'blockers', v_blockers
  );
end;
$$;

