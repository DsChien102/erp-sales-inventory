create or replace function einvoice.claim_internal_commands_batch(
  p_tenant_id uuid,
  p_limit int default 10
)
returns table (
  command_id uuid,
  command_type text,
  payload jsonb,
  source_event_id uuid,
  enqueued_at timestamptz,
  claim_token uuid,
  retry_count int
)
language plpgsql
security definer
set search_path = einvoice, platform, pg_temp
as $$
begin
  return query
  with candidates as (
    select m.id
    from einvoice.internal_commands m
    where m.tenant_id = p_tenant_id
      and m.processed_at is null
      and m.failed_at is null
      and m.enqueued_at <= now()
      and (
        m.claimed_at is null
        or m.claimed_at < now() - interval '10 minutes'
      )
    order by m.enqueued_at
    for update skip locked
    limit greatest(p_limit, 1)
  ),
  updated as (
    update einvoice.internal_commands m
    set
      claimed_at = now(),
      claim_token = gen_random_uuid()
    from candidates c
    where m.id = c.id
    returning
      m.id,
      m.command_type,
      m.payload,
      m.source_event_id,
      m.enqueued_at,
      m.claim_token,
      m.retry_count
  )
  select
    u.id,
    u.command_type,
    u.payload,
    u.source_event_id,
    u.enqueued_at,
    u.claim_token,
    u.retry_count
  from updated u;
end;
$$;

create or replace function einvoice.retry_or_dead_letter_internal_command(
  p_tenant_id uuid,
  p_command_id uuid,
  p_claim_token uuid,
  p_error text
)
returns table (
  disposition text,
  retry_count int
)
language plpgsql
security definer
set search_path = einvoice, platform, pg_temp
as $$
declare
  v_cmd einvoice.internal_commands%rowtype;
  v_next_retry_count int;
  v_disposition text;
begin
  select *
  into v_cmd
  from einvoice.internal_commands
  where id = p_command_id
    and tenant_id = p_tenant_id
    and claim_token = p_claim_token
    and processed_at is null
  for update;

  if not found then
    raise exception 'NOT_FOUND: internal command or claim token mismatch';
  end if;

  v_next_retry_count := v_cmd.retry_count + 1;

  if v_next_retry_count >= 3 then
    v_disposition := 'DEAD_LETTER';
    update einvoice.internal_commands
    set
      failed_at = now(),
      error = p_error,
      retry_count = v_next_retry_count,
      claimed_at = null,
      claim_token = null
    where id = p_command_id;
  else
    v_disposition := 'RETRY';
    update einvoice.internal_commands
    set
      error = p_error,
      retry_count = v_next_retry_count,
      enqueued_at = now() + (case when v_cmd.retry_count = 0 then interval '5 seconds' else interval '30 seconds' end),
      claimed_at = null,
      claim_token = null
    where id = p_command_id;
  end if;

  return query select v_disposition, v_next_retry_count;
end;
