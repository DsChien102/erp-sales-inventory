begin
  if p_request.result_type is null then
    raise exception 'Remembered price request % has no terminal outcome.', p_request.id;
  end if;

  if p_request.result_type in ('created', 'updated') then
    if p_request.rule_id is null or p_request.rule_version is null then
      raise exception 'Successful remembered price request % is inconsistent.', p_request.id;
    end if;
  elsif p_request.result_type in ('skipped', 'blocked') then
    if p_request.reason_code is null then
      raise exception 'Skipped or blocked remembered price request % is inconsistent.', p_request.id;
    end if;
  end if;

  return jsonb_build_object(
    'request_id', p_request.id,
    'result_type', p_request.result_type,
    'rule_id', p_request.rule_id,
    'rule_version', p_request.rule_version,
    'reason_code', p_request.reason_code,
    'warnings', coalesce(p_request.warnings, '[]'::jsonb),
    'is_replay', coalesce(p_is_replay, false)
  );
end;
$$;

