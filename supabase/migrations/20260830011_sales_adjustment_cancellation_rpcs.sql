declare
  v_order sales.sales_orders%rowtype;
  v_cancellation sales.sales_order_cancellations%rowtype;
  v_cancel_actor_id uuid;
  v_cancel_actor_name text;
begin
  if auth.uid() is distinct from actor_id
    or iam.has_permission(tenant_id, 'sales.order.view') is not true then
    raise exception using message = jsonb_build_object(
      'code', 'PERMISSION_DENIED', 'message', 'Permission denied.'
    )::text;
  end if;

  select * into v_order
  from sales.sales_orders
  where sales_orders.id = get_sales_order_cancellation.sales_order_id
    and sales_orders.tenant_id = get_sales_order_cancellation.tenant_id;
  if not found then
    raise exception using message = jsonb_build_object(
      'code', 'NOT_FOUND', 'message', 'Sales order not found.',
      'details', jsonb_build_object('salesOrderId', sales_order_id)
    )::text;
  end if;

  if expected_source_version is not null
     and v_order.version is distinct from expected_source_version then
    raise exception using message = jsonb_build_object(
      'code', 'STALE_VERSION', 'message', 'Sales order version is stale.'
    )::text;
  end if;

  if not iam.can_access_store(get_sales_order_cancellation.tenant_id, v_order.store_id, get_sales_order_cancellation.actor_id) then
    raise exception using message = jsonb_build_object(
      'code', 'DATA_SCOPE_DENIED', 'message', 'Store scope denied.'
    )::text;
  end if;

  select * into v_cancellation
  from sales.sales_order_cancellations c
  where c.tenant_id = get_sales_order_cancellation.tenant_id
    and c.sales_order_id = get_sales_order_cancellation.sales_order_id
    and c.status in ('confirmed', 'processing', 'completed')
  order by coalesce(c.confirmed_at, c.created_at) desc, c.id desc
  limit 1;
  if not found then
    raise exception using message = jsonb_build_object(
      'code', 'NOT_FOUND', 'message', 'Sales order cancellation not found.'
    )::text;
  end if;

  v_cancel_actor_id := coalesce(
    v_cancellation.confirmed_by_user_id,
    v_cancellation.requested_by_user_id
  );

  select coalesce(
    nullif(trim(concat_ws(' ', p.given_name, p.family_middle_name)), ''),
    nullif(trim(concat_ws(' ', u.raw_user_meta_data->>'first_name', u.raw_user_meta_data->>'last_name')), ''),
    nullif(trim(concat_ws(' ', u.raw_user_meta_data->>'last_name', u.raw_user_meta_data->>'first_name')), ''),
    nullif(trim(u.email::text), '')
  )
  into v_cancel_actor_name
  from (select v_cancel_actor_id as user_id) actor
  left join iam.platform_user_profiles p on p.user_id = actor.user_id
  left join auth.users u on u.id = actor.user_id;

  return jsonb_build_object(
    'result', jsonb_build_object(
      'cancellationId', v_cancellation.id,
      'salesOrderId', v_cancellation.sales_order_id,
      'salesOrderVersion', coalesce(
        (v_cancellation.precheck_snapshot ->> 'resultingOrderVersion')::bigint,
        v_cancellation.source_order_version + 1
      ),
      'status', v_cancellation.status
    ),
    'reason', jsonb_build_object(
      'reasonText', coalesce(v_cancellation.reason, '')
    ),
    'cancelledAt', to_char(
      coalesce(v_cancellation.confirmed_at, v_cancellation.created_at) at time zone 'utc',
      'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'
    ),
    'cancelledByActorId', v_cancel_actor_id,
    'cancelledByActorName', coalesce(v_cancel_actor_name, ''),
    'netConfirmedCollectionMinor', coalesce(
      (v_cancellation.precheck_snapshot ->> 'netConfirmedCollectionMinor')::bigint,
      0
    )
  );
end;
$$;

create or replace function sales.list_sales_order_cancellation_reasons(
  query_id text,
  tenant_id uuid,
  actor_id uuid
) returns jsonb
language plpgsql
security definer
set search_path = sales, iam, public, pg_temp
as $$
declare
  v_items jsonb;
begin
  if auth.uid() is distinct from actor_id
    or iam.has_permission(tenant_id, 'sales.order.cancel') is not true then
    raise exception using message = jsonb_build_object(
      'code', 'PERMISSION_DENIED', 'message', 'Permission denied.'
    )::text;
  end if;

  select jsonb_agg(
      jsonb_build_object(
        'reasonCode', reasons.reason_code,
        'displayName', reasons.display_name,
        'requiresNote', reasons.requires_note,
        'sortOrder', reasons.sort_order
      )
      order by reasons.sort_order, reasons.reason_code
  )
  into v_items
  from (
    values
      ('CUSTOMER_REQUEST', 'Khách yêu cầu hủy', false, 10),
      ('DUPLICATE', 'Tạo trùng đơn', false, 20),
      ('OTHER', 'Lý do khác', true, 99)
  ) as reasons(reason_code, display_name, requires_note, sort_order);

  return jsonb_build_object('items', v_items);
end;
$$;

