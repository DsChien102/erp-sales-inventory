create or replace function iam.create_tenant_onboarding(
  p_owner_user_id uuid,
  p_org_name text,
  p_idempotency_key text,
  p_correlation_id text default null,
  p_is_new_user boolean default false,
  p_owner_email text default null,
  p_owner_given_name text default null,
  p_owner_family_name text default null,
  p_owner_phone text default null,
  p_org_display_name text default null,
  p_org_contact_email text default null,
  p_org_contact_phone text default null,
  p_org_contact_address_text text default null,
  p_org_province_code text default null,
  p_org_commune_code text default null,
  p_org_legal_name text default null,
  p_org_tax_code text default null,
  p_org_registered_address_text text default null
)
returns jsonb
language plpgsql
security definer
set search_path = iam, pg_temp
as $$
declare
  v_actor uuid := auth.uid();
  v_existing jsonb;
  v_tenant_id uuid;
  v_correlation text;
  v_owner_email text;
  v_owner_email_masked text;
  v_owner_role_id uuid;
  v_invitation_id uuid;
  v_org_legal_name text := nullif(trim(coalesce(p_org_legal_name, '')), '');
  v_org_tax_code text := nullif(trim(coalesce(p_org_tax_code, '')), '');
  v_org_registered_address_text text :=
    nullif(trim(coalesce(p_org_registered_address_text, '')), '');
  v_message_id uuid := gen_random_uuid();
  v_outcome_id uuid := gen_random_uuid();
  v_now timestamptz := now();
  v_is_new boolean := coalesce(p_is_new_user, false);
  v_provisioned_user_id uuid;
  v_raw_code text;
  v_code_hash text;
  v_ciphertext text;
  v_result jsonb;
begin
  if not iam.has_platform_permission('platform.tenant.create') then
    raise exception 'platform permission denied';
  end if;

  if p_org_name is null or trim(p_org_name) = '' then
    raise exception 'organization name required';
  end if;

  if p_idempotency_key is null or trim(p_idempotency_key) = '' then
    raise exception 'idempotency key required';
  end if;

  if v_is_new then
    v_owner_email := lower(trim(coalesce(p_owner_email, '')));
    if v_owner_email = '' or position('@' in v_owner_email) = 0 then
      raise exception 'owner email required';
    end if;
  else
    if p_owner_user_id is null then
      raise exception 'owner user id required';
    end if;
  end if;

  select result into v_existing
  from iam.onboarding_operations
  where idempotency_key = p_idempotency_key;

  if v_existing is not null then
    return v_existing;
  end if;

  v_correlation := coalesce(nullif(trim(p_correlation_id), ''), gen_random_uuid()::text);

  insert into iam.tenants (
    name, display_name, contact_email, contact_phone, contact_address_text,
    province_code, commune_code, status, updated_at
  )
  values (
    trim(p_org_name),
    coalesce(nullif(trim(coalesce(p_org_display_name, '')), ''), trim(p_org_name)),
    nullif(trim(coalesce(p_org_contact_email, '')), ''),
    nullif(trim(coalesce(p_org_contact_phone, '')), ''),
    nullif(trim(coalesce(p_org_contact_address_text, '')), ''),
    nullif(trim(coalesce(p_org_province_code, '')), ''),
    nullif(trim(coalesce(p_org_commune_code, '')), ''),
    'provisioning',
    v_now
  )
  returning id into v_tenant_id;

  if v_org_legal_name is not null and v_org_tax_code is not null then
    insert into iam.tenant_legal_profiles (
      tenant_id, legal_entity_type, legal_name, tax_code,
      registered_address_text, province_code, commune_code, created_at, updated_at
    )
    values (
      v_tenant_id,
      case
        when length(regexp_replace(v_org_tax_code, '\D', '', 'g')) = 12
          then 'HOUSEHOLD_BUSINESS'
        else 'ENTERPRISE'
      end,
      v_org_legal_name,
      v_org_tax_code,
      v_org_registered_address_text,
      nullif(trim(coalesce(p_org_province_code, '')), ''),
      nullif(trim(coalesce(p_org_commune_code, '')), ''),
      v_now, v_now
    );
  end if;

  perform iam.enqueue_outbox_message(
    v_tenant_id,
    'iam.tenant.created',
    jsonb_build_object(
      'tenant_id', v_tenant_id,
      'owner_user_id', p_owner_user_id,
      'actor_user_id', v_actor,
      'correlation_id', v_correlation
    )
  );

  -- Owner email: owner cũ resolve từ auth.users; owner mới lấy từ tham số.
  if not v_is_new then
    select lower(u.email::text) into v_owner_email
    from auth.users u
    where u.id = p_owner_user_id;
    if v_owner_email is null or trim(v_owner_email) = '' then
      raise exception 'owner email required';
    end if;
  end if;

  -- Owner mới: tạo pending platform_user_profiles NGAY (owner đã "vào hệ thống",
  -- chỉ chưa active) để hiện trong danh sách Platform Users trước khi kích hoạt.
  -- auth.users chưa có → dùng id tạm; reconcile khi owner signUp (trigger dọn
  -- placeholder + accept tạo profile active). Idempotent: reuse nếu email đã có
  -- auth user hoặc đã có profile.
  if v_is_new then
    select u.id into v_provisioned_user_id
    from auth.users u
    where lower(u.email::text) = v_owner_email
    limit 1;

    if v_provisioned_user_id is null then
      select p.user_id into v_provisioned_user_id
      from iam.platform_user_profiles p
      where lower(p.email) = v_owner_email
      limit 1;
    end if;

    if v_provisioned_user_id is null then
      v_provisioned_user_id := gen_random_uuid();
      insert into iam.platform_user_profiles (
        user_id, email, status, given_name, family_middle_name, phone_number,
        created_at, updated_at
      )
      values (
        v_provisioned_user_id,
        v_owner_email,
        'pending_activation',
        nullif(trim(coalesce(p_owner_given_name, '')), ''),
        nullif(trim(coalesce(p_owner_family_name, '')), ''),
        nullif(trim(coalesce(p_owner_phone, '')), ''),
        v_now, v_now
      );
    end if;
  end if;

  -- initial_role_id cho lời mời owner. accept_invitation sẽ override sang
  -- store_owner qua v_should_be_owner, nhưng cột này là FK nên cần role hợp lệ.
  select id into v_owner_role_id
  from iam.role_definitions
  where code = 'store_owner' and status = 'active';
  if v_owner_role_id is null then
    raise exception 'store_owner role missing';
  end if;

  -- Mã kích hoạt owner (worker gửi) — lưu trong tenant_invitations.token_hash.
  v_raw_code := iam._generate_invitation_code();
  v_code_hash := iam._invitation_token_hash(v_raw_code);
  v_ciphertext := 'transient:' || encode(convert_to(v_raw_code, 'UTF8'), 'base64');

  -- Lời mời OWNER (is_owner, không có người mời). Membership tạo lúc accept.
  insert into iam.tenant_invitations (
    tenant_id, invitee_email, initial_role_id, status, token_hash,
    is_owner, invited_by_membership_id, given_name, family_name, phone,
    expires_at, status_changed_at, version, created_at, updated_at, delivery_correlation_id
  )
  values (
    v_tenant_id, v_owner_email, v_owner_role_id, 'pending', v_code_hash,
    true, null,
    nullif(trim(coalesce(p_owner_given_name, '')), ''),
    nullif(trim(coalesce(p_owner_family_name, '')), ''),
    nullif(trim(coalesce(p_owner_phone, '')), ''),
    v_now + interval '7 days', v_now,
    1, v_now, v_now, v_correlation
  )
  returning id into v_invitation_id;

  v_owner_email_masked :=
    left(v_owner_email, 1) || '***' ||
    substring(v_owner_email from position('@' in v_owner_email));

  perform iam.enqueue_outbox_message(
    v_tenant_id,
    'iam.email.delivery_requested',
    jsonb_build_object(
      'event_version', 1,
      'id', v_message_id,
      'occurred_on', v_now,
      'tenant_id', v_tenant_id,
      'template_id', 'activation_invitation',
      'to_email', v_owner_email,
      'correlation_id', v_correlation,
      'outcome_id', v_outcome_id,
      'locale', 'vi',
      'refs', jsonb_build_object(
        'tenant_id', v_tenant_id::text,
        'invitation_id', v_invitation_id::text
      ),
      'secret_payload_ciphertext', v_ciphertext
    ),
    v_message_id
  );

  v_raw_code := null;

  perform iam.record_email_delivery_outcome(
    p_correlation_id := v_correlation,
    p_template_id := 'activation_invitation',
    p_status := 'queued',
    p_tenant_id := v_tenant_id,
    p_to_email_masked := v_owner_email_masked,
    p_id := v_outcome_id
  );

  v_result := jsonb_build_object(
    'tenant_id', v_tenant_id,
    'owner_membership_id', null,
    'owner_user_id', p_owner_user_id,
    'tenant_status', 'provisioning',
    'correlation_id', v_correlation,
    'is_new_user', v_is_new,
    'activation_issued', true
  );

  insert into iam.onboarding_operations (idempotency_key, correlation_id, result)
  values (p_idempotency_key, v_correlation, v_result);

  return v_result;
end;
$$;

-- accept_invitation: staff + owner dùng CHUNG. Gỡ fallback owner-activation cũ
-- (mã owner giờ là một dòng tenant_invitations, đi qua nhánh chính). Người active
-- đầu tiên tự thành store_owner + is_owner qua v_should_be_owner.
create or replace function iam.accept_invitation(
  p_token text,
  p_idempotency_key text
)
returns jsonb
language plpgsql
security definer
set search_path = iam, pg_temp
as $$
declare
  v_caller uuid := auth.uid();
  v_inv iam.tenant_invitations;
  v_tenant iam.tenants;
  v_role iam.role_definitions;
  v_hash text;
  v_email text;
  v_payload_hash text;
  v_existing iam.idempotency_records;
  v_membership iam.memberships;
  v_effective_role text;
  v_should_be_owner boolean := false;
  v_now timestamptz := now();
  v_result jsonb;
  v_audit_before jsonb;
begin
  if v_caller is null then
    raise exception 'AUTHENTICATION_REQUIRED';
  end if;

  if p_idempotency_key is null or trim(p_idempotency_key) = '' then
    raise exception 'VALIDATION_ERROR';
  end if;

  v_hash := iam._invitation_token_hash(p_token);
  v_payload_hash := md5(v_hash || '|accept');

  select * into v_existing
  from iam.tenant_invitation_token_operations o
  where o.token_hash = v_hash
    and o.operation = 'accept'
    and o.idempotency_key = p_idempotency_key;

  if found then
    if v_existing.payload_hash <> v_payload_hash then
      raise exception 'IDEMPOTENCY_CONFLICT';
    end if;
    return v_existing.result;
  end if;

  -- Token phải là một lời mời hợp lệ (staff HOẶC owner); nếu không →
  -- INVITATION_TOKEN_INVALID (không còn fallback đọc bảng kích hoạt cũ).
  v_inv := iam._load_invitation_by_token(p_token);

  select * into v_tenant from iam.tenants t where t.id = v_inv.tenant_id for update;
  if not found then
    raise exception 'INVITATION_TOKEN_INVALID';
  end if;

  if coalesce(v_tenant.status, 'active') = 'suspended' then
    raise exception 'TENANT_SUSPENDED';
  end if;

  if v_inv.status = 'revoked' then
    raise exception 'INVITATION_REVOKED';
  end if;
  if v_inv.status in ('accepted', 'declined') then
    raise exception 'INVITATION_ALREADY_USED';
  end if;
  if v_inv.status = 'expired' or v_inv.expires_at <= v_now then
    raise exception 'INVITATION_EXPIRED';
  end if;
  if v_inv.status <> 'pending' then
    raise exception 'INVITATION_TOKEN_INVALID';
  end if;

  select lower(trim(u.email::text)) into v_email
  from auth.users u
  where u.id = v_caller;

  if v_email is null or v_email <> v_inv.invitee_email then
    raise exception 'INVITATION_EMAIL_MISMATCH';
  end if;

  if exists (
    select 1 from iam.memberships m
    where m.tenant_id = v_inv.tenant_id
      and m.user_id = v_caller
      and m.is_active
  ) then
    raise exception 'DUPLICATE_MEMBERSHIP';
  end if;

  select * into v_role from iam.role_definitions r where r.id = v_inv.initial_role_id;
  if not found or v_role.status <> 'active' then
    raise exception 'ROLE_NOT_ASSIGNABLE';
  end if;

  v_audit_before := jsonb_build_object(
    'invitation_id', v_inv.id,
    'status', v_inv.status,
    'version', v_inv.version
  );

  -- Người active đầu tiên của tenant là chủ: is_owner + role store_owner.
  v_should_be_owner := not exists (
    select 1
    from iam.memberships m
    where m.tenant_id = v_inv.tenant_id
      and m.is_active
      and m.is_owner is true
  );
  v_effective_role := case
    when v_should_be_owner then 'store_owner'
    else coalesce(v_role.code, 'staff')
  end;

  insert into iam.memberships (
    tenant_id, user_id, role, is_owner, version, created_at, updated_at
  )
  values (
    v_inv.tenant_id, v_caller, v_effective_role, v_should_be_owner, 1, v_now, v_now
  )
  returning * into v_membership;

  update iam.tenant_invitations
  set
    status = 'accepted',
    accepted_membership_id = v_membership.id,
    status_changed_at = v_now,
    version = version + 1,
    updated_at = v_now,
    token_hash = encode(extensions.digest(extensions.gen_random_bytes(32), 'sha256'), 'hex')
  where id = v_inv.id
  returning * into v_inv;

  -- Owner (người active đầu tiên): tạo/kích hoạt platform_user_profiles với tên
  -- từ lời mời (admin đã nhập lúc onboarding) để Platform Admin hiển thị đúng
  -- tên, tránh "Chưa xác định owner". Staff không có profile platform ở đây.
  if v_should_be_owner then
    insert into iam.platform_user_profiles (
      user_id, email, status, email_verified, given_name, family_middle_name,
      phone_number, created_at, updated_at
    )
    values (
      v_caller, v_email, 'active', true, v_inv.given_name, v_inv.family_name, v_inv.phone,
      v_now, v_now
    )
    on conflict (user_id) do update
      set status = 'active',
          email = coalesce(excluded.email, iam.platform_user_profiles.email),
          email_verified = true,
          given_name = coalesce(excluded.given_name, iam.platform_user_profiles.given_name),
          family_middle_name = coalesce(
            excluded.family_middle_name, iam.platform_user_profiles.family_middle_name
          ),
          phone_number = coalesce(excluded.phone_number, iam.platform_user_profiles.phone_number),
          updated_at = v_now;
  end if;

  v_result := iam._membership_detail_json(v_membership);

  perform iam.append_audit_log(
    p_scope => 'tenant',
    p_tenant_id => v_inv.tenant_id,
    p_actor_user_id => v_caller,
    p_event_code => 'iam.tenant.invitation_accepted',
    p_subject_type => 'tenant',
    p_subject_id => v_inv.tenant_id::text,
    p_result => 'success',
    p_source => 'iam',
    p_tracking_id => p_idempotency_key,
    p_before => v_audit_before,
    p_after => jsonb_build_object(
      'invitation_id', v_inv.id,
      'status', v_inv.status,
      'membership_id', v_membership.id,
      'version', v_inv.version
    ),
    p_actor_type => 'tenant_member',
    p_actor_membership_id => v_membership.id,
    p_actor_display_name => nullif(
      trim(concat_ws(' ', v_inv.family_name, v_inv.given_name)),
      ''
    ),
    p_actor_context_label => coalesce(v_role.label, v_effective_role),
    p_actor_snapshot => jsonb_build_object(
      'display_name', nullif(
        trim(concat_ws(' ', v_inv.family_name, v_inv.given_name)),
        ''
      ),
      'actor_type', 'tenant_member',
      'role_code', v_effective_role,
      'role_label', coalesce(v_role.label, v_effective_role)
    ),
    p_target_display_name => v_tenant.display_name,
    p_target_secondary_identifier => v_tenant.code,
    p_target_snapshot => jsonb_build_object(
      'display_name', v_tenant.display_name,
      'subject_code', v_tenant.code,
      'secondary_label', v_tenant.code
    ),
    p_correlation_id => p_idempotency_key,
    p_detail_items => jsonb_build_array(
      jsonb_build_object(
        'field_key', 'status',
        'before', v_audit_before->'status',
        'after', to_jsonb(v_inv.status)
      ),
      jsonb_build_object(
        'field_key', 'membership_id',
        'before', null,
        'after', to_jsonb(v_membership.id)
      )
    )
  );

  insert into iam.tenant_invitation_token_operations (
    token_hash, operation, idempotency_key, payload_hash, result
  ) values (
    v_hash, 'accept', p_idempotency_key, v_payload_hash, v_result
  );

  return v_result;
end;
$$;

-- inspect_invitation_token: staff + owner dùng chung. Gỡ fallback owner-activation.
create or replace function iam.inspect_invitation_token(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = iam, pg_temp
as $$
declare
  v_inv iam.tenant_invitations;
  v_role iam.role_definitions;
  v_tenant iam.tenants;
  v_account_exists boolean := false;
  v_should_be_owner boolean := false;
  v_now timestamptz := now();
begin
  -- Token phải là một lời mời hợp lệ; nếu không → INVITATION_TOKEN_INVALID.
  v_inv := iam._load_invitation_by_token(p_token);

  if v_inv.status = 'revoked' then
    raise exception 'INVITATION_REVOKED';
  end if;
  if v_inv.status in ('accepted', 'declined') then
    raise exception 'INVITATION_ALREADY_USED';
  end if;
  if v_inv.status = 'expired' or v_inv.expires_at <= v_now then
    raise exception 'INVITATION_EXPIRED';
  end if;
  if v_inv.status <> 'pending' then
    raise exception 'INVITATION_TOKEN_INVALID';
  end if;

  select * into v_tenant from iam.tenants t where t.id = v_inv.tenant_id;
  select * into v_role from iam.role_definitions r where r.id = v_inv.initial_role_id;

  v_should_be_owner := not exists (
    select 1
    from iam.memberships m
    where m.tenant_id = v_inv.tenant_id
      and m.is_active
      and m.is_owner is true
  );

  select exists (
    select 1 from auth.users u
    where lower(trim(u.email::text)) = v_inv.invitee_email
  ) into v_account_exists;

  return jsonb_build_object(
    'tenant_id', v_inv.tenant_id,
    'tenant_name', coalesce(v_tenant.name, ''),
    'invitee_email', v_inv.invitee_email,
    'initial_role_id', case when v_should_be_owner then 'owner' else v_inv.initial_role_id::text end,
    'initial_role_label', case when v_should_be_owner then 'Chủ sở hữu' else coalesce(v_role.label, '') end,
    'expires_at', v_inv.expires_at,
    'account_exists', v_account_exists,
    'given_name', v_inv.given_name,
    'family_name', v_inv.family_name,
    'phone', v_inv.phone
  );
end;
$$;

revoke all on function iam.inspect_invitation_token(text) from public;
grant execute on function iam.inspect_invitation_token(text) to anon, authenticated;

-- resend_owner_activation: Platform Admin "Gửi lại email kích hoạt" cho owner.
-- Owner Design A kích hoạt bằng mã trong tenant_invitations (như staff), nhưng
-- do Platform Admin kích (không phải member trong tenant) nên cần RPC platform-
-- level riêng. Dùng CHUNG cơ chế với resend_tenant_invitation: xoay token (mã
-- mới) + gia hạn 7 ngày + enqueue email 'activation_invitation'. Tìm lời mời
-- owner theo email của platform user (placeholder pending chưa có auth.users,
-- hoặc auth.users đã có).
create or replace function iam.resend_owner_activation(
  p_user_id uuid,
  p_idempotency_key text
)
returns void
language plpgsql
security definer
set search_path = iam, auth, pg_temp
as $$
declare
  v_email text;
  v_inv iam.tenant_invitations;
  v_raw_code text;
  v_code_hash text;
  v_ciphertext text;
  v_now timestamptz := now();
  v_message_id uuid := gen_random_uuid();
  v_outcome_id uuid := gen_random_uuid();
  v_correlation text := gen_random_uuid()::text;
  v_masked text;
begin
  if not iam.has_platform_permission('platform.user.activation_invite.send') then
    raise exception 'PLATFORM_PERMISSION_DENIED';
  end if;
  if p_idempotency_key is null or trim(p_idempotency_key) = '' then
    raise exception 'VALIDATION_ERROR';
  end if;

  -- Email của user: auth.users (đã kích hoạt) HOẶC placeholder profile (pending).
  select coalesce(lower(u.email::text), lower(p.email)) into v_email
  from iam.platform_user_profiles p
  full outer join auth.users u on u.id = p.user_id
  where coalesce(u.id, p.user_id) = p_user_id
  limit 1;
  if v_email is null or trim(v_email) = '' then
    raise exception 'RESOURCE_NOT_FOUND';
  end if;

  -- Lời mời OWNER đang pending khớp email.
  select * into v_inv
  from iam.tenant_invitations i
  where i.is_owner = true
    and i.status = 'pending'
    and lower(i.invitee_email) = v_email
  order by i.created_at desc
  limit 1;
  if not found then
    raise exception 'RESOURCE_NOT_FOUND';
  end if;

  -- Xoay mã + gia hạn + gửi lại (giống resend_tenant_invitation).
  v_raw_code := iam._generate_invitation_code();
  v_code_hash := iam._invitation_token_hash(v_raw_code);
  v_ciphertext := 'transient:' || encode(convert_to(v_raw_code, 'UTF8'), 'base64');
  v_masked := left(v_email, 1) || '***' ||
    substring(v_email from position('@' in v_email));

  update iam.tenant_invitations
  set token_hash = v_code_hash,
      expires_at = v_now + interval '7 days',
      status_changed_at = v_now,
      version = version + 1,
      updated_at = v_now,
      delivery_correlation_id = v_correlation,
      last_sent_at = v_now
  where id = v_inv.id;

  perform iam.enqueue_outbox_message(
    v_inv.tenant_id,
    'iam.email.delivery_requested',
    jsonb_build_object(
      'event_version', 1,
      'id', v_message_id,
      'occurred_on', v_now,
      'tenant_id', v_inv.tenant_id,
      'template_id', 'activation_invitation',
      'to_email', v_email,
      'correlation_id', v_correlation,
      'outcome_id', v_outcome_id,
      'locale', 'vi',
      'refs', jsonb_build_object(
        'tenant_id', v_inv.tenant_id::text,
        'invitation_id', v_inv.id::text
      ),
      'secret_payload_ciphertext', v_ciphertext
    ),
    v_message_id
  );
  v_raw_code := null;

  perform iam.record_email_delivery_outcome(
    p_correlation_id := v_correlation,
    p_template_id := 'activation_invitation',
    p_status := 'queued',
    p_tenant_id := v_inv.tenant_id,
    p_to_email_masked := v_masked,
    p_id := v_outcome_id
  );
end;
$$;

revoke all on function iam.resend_owner_activation(uuid, text) from public, anon;
grant execute on function iam.resend_owner_activation(uuid, text) to authenticated;

