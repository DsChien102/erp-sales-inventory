-- Active profiles keep a queryable copy of the Auth email. Auth remains the
-- authority; this backfill repairs rows created by older activation/login paths.
update iam.platform_user_profiles p
set email = lower(trim(u.email::text)),
    updated_at = now()
from auth.users u
where u.id = p.user_id
  and u.email is not null
  and p.email is distinct from lower(trim(u.email::text));

create or replace function iam.record_my_platform_login()
returns void
language plpgsql
security definer
set search_path = iam, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_email text;
begin
  if v_user_id is null then
    raise exception 'authentication required';
  end if;

  select lower(trim(u.email::text))
  into v_email
  from auth.users u
  where u.id = v_user_id;

  insert into iam.platform_user_profiles (
    user_id, email, status, last_login_at, created_at, updated_at
  )
  values (
    v_user_id, v_email, 'active', now(), now(), now()
  )
  on conflict (user_id) do update
    set email = coalesce(excluded.email, iam.platform_user_profiles.email),
        last_login_at = now(),
        updated_at = now();
end;
$$;

revoke all on function iam.record_my_platform_login() from public, anon;
grant execute on function iam.record_my_platform_login() to authenticated;

-- inspect_invitation_token: đọc lời mời theo mã để màn nhận lời mời hiển thị (anon được gọi).
create or replace function iam.inspect_invitation_token(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = iam, pg_temp
as $$
declare
  v_inv iam.tenant_invitations;
  v_role iam.role_definitions;
  v_tenant iam.tenants;
  v_account_exists boolean := false;
  v_now timestamptz := now();
begin
  -- Token phải là một lời mời hợp lệ; nếu không → INVITATION_TOKEN_INVALID.
  v_inv := iam._load_invitation_by_token(p_token);

  select * into v_tenant from iam.tenants t where t.id = v_inv.tenant_id;

  if v_inv.status = 'revoked' then
    raise exception 'INVITATION_REVOKED';
  end if;
  if v_inv.status in ('accepted', 'declined') then
    raise exception 'INVITATION_ALREADY_USED';
  end if;
  if v_inv.status = 'expired' or v_inv.expires_at <= v_now then
    raise exception 'INVITATION_EXPIRED';
  end if;
  if v_inv.status <> 'pending' then
    raise exception 'INVITATION_TOKEN_INVALID';
  end if;

  select * into v_role from iam.role_definitions r where r.id = v_inv.initial_role_id;

  select exists (
    select 1 from auth.users u
    where lower(trim(u.email::text)) = v_inv.invitee_email
  ) into v_account_exists;

  return jsonb_build_object(
    'tenant_id', v_inv.tenant_id,
    'tenant_name', coalesce(v_tenant.display_name, ''),
    'invitee_email', v_inv.invitee_email,
    'initial_role_id', v_inv.initial_role_id::text,
    'initial_role_label', coalesce(v_role.label, ''),
    'expires_at', v_inv.expires_at,
    'account_exists', v_account_exists,
    'given_name', v_inv.given_name,
    'family_name', v_inv.family_name,
    'phone', v_inv.phone
  );
end;
$$;

revoke all on function iam.inspect_invitation_token(text) from public;
grant execute on function iam.inspect_invitation_token(text) to anon, authenticated;
