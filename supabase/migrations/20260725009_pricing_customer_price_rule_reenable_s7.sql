create or replace function pricing.reenable_customer_price_rule(
  p_tenant_id uuid,
  p_rule_id uuid,
  p_expected_version integer,
  p_business_date date,
  p_precheck_token text default null,
  p_acknowledge_floor_warning boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor_id uuid := auth.uid();
  v_rule pricing.customer_price_rules%rowtype;
  v_context jsonb;
  v_current_token text;
  v_blocking_codes jsonb;
  v_result jsonb;
  v_old_value jsonb;
begin
  if v_actor_id is null
    or not iam.has_permission(
      p_tenant_id,
      'pricing.customer_price_rule.reenable'
    ) then
    perform pricing._raise_pricing_error(
      'NO_PERMISSION',
      'Permission denied.',
      jsonb_build_object('permission', 'pricing.customer_price_rule.reenable')
    );
  end if;

  if p_tenant_id is null
    or p_rule_id is null
    or p_expected_version is null
    or p_expected_version <= 0
    or p_business_date is null
    or (
      p_precheck_token is not null
      and p_precheck_token !~ '^[0-9a-f]{64}$'
    ) then
    perform pricing._raise_pricing_error(
      'VALIDATION_ERROR',
      'Invalid customer price rule reenable payload.'
    );
  end if;

  select r.*
  into v_rule
  from pricing.customer_price_rules r
  where r.tenant_id = p_tenant_id
    and r.id = p_rule_id
    and r.status <> 'deleted'
  for update;

  if not found then
    perform pricing._raise_pricing_error(
      'NOT_FOUND',
      'Customer price rule was not found.'
    );
  end if;

  if v_rule.version <> p_expected_version then
    perform pricing._raise_pricing_error(
      'STATE_CHANGED',
      'Customer price rule version changed.',
      jsonb_build_object(
        'expectedVersion', p_expected_version,
        'currentVersion', v_rule.version
      )
    );
  end if;

  if v_rule.status <> 'disabled' then
    perform pricing._raise_pricing_error(
      'INVALID_STATUS',
      'Only a disabled customer price rule can be reenabled.',
      jsonb_build_object('status', v_rule.status)
    );
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(
      p_tenant_id::text || ':rule:' || v_rule.customer_id::text || ':'
        || v_rule.product_id::text || ':' || v_rule.product_unit_id::text,
      0
    )
  );

  v_context := pricing._customer_price_rule_reenable_context(
    p_tenant_id,
    p_rule_id,
    v_actor_id,
    p_business_date
  );

  v_current_token := v_context ->> 'precheck_token';
  if p_precheck_token is not null
    and v_current_token <> p_precheck_token then
    perform pricing._raise_pricing_error(
      'STATE_CHANGED',
      'Customer price rule reenable precheck is stale.',
      jsonb_build_object(
        'reason', 'precheckStale',
        'expectedVersion', p_expected_version,
        'currentVersion', v_rule.version
      )
    );
  end if;

  v_blocking_codes := v_context #> '{validation_outcome,blocking_codes}';

  if v_blocking_codes ?| array[
    'customer_reference_invalid',
    'product_unit_reference_invalid',
    'currency_mismatch'
  ] then
    perform pricing._raise_pricing_error(
      'REFERENCE_INVALID',
      'Customer price rule references are not valid for reenable.'
    );
  end if;

  if coalesce((v_context ->> 'is_expired')::boolean, false) then
    perform pricing._raise_pricing_error(
      'INVALID_STATUS',
      'Customer price rule effective period has expired.',
      jsonb_build_object('reason', 'effectivePeriodExpired')
    );
  end if;

  if coalesce((v_context ->> 'is_below_floor')::boolean, false)
    and (
      not coalesce(p_acknowledge_floor_warning, false)
      or not coalesce((v_context ->> 'can_override_floor')::boolean, false)
    ) then
    perform pricing._raise_pricing_error(
      'BELOW_FLOOR_BLOCKED',
      'Below-floor price requires acknowledgement and override permission.',
      jsonb_build_object(
        'reason', case
          when not coalesce((v_context ->> 'can_override_floor')::boolean, false)
            then 'override_permission_required'
          else 'acknowledgement_required'
        end
      )
    );
  end if;

  perform pricing._auto_disable_overlapping_customer_price_rules(
    p_tenant_id,
    p_rule_id,
    v_rule.customer_id,
    v_rule.product_id,
    v_rule.product_unit_id,
    v_rule.effective_from,
    v_rule.effective_to,
    v_actor_id,
    'reenabled'
  );

  v_old_value := jsonb_build_object(
    'status', v_rule.status,
    'version', v_rule.version,
    'disabled_at', v_rule.disabled_at,
    'disabled_by', v_rule.disabled_by,
    'disabled_reason', v_rule.disabled_reason
  );

  update pricing.customer_price_rules
  set status = 'active',
      customer_display_name_snapshot =
        v_context #>> '{customer_snapshot,display_name}',
      customer_status_snapshot =
        v_context #>> '{customer_snapshot,status}',
      product_name_snapshot =
        v_context #>> '{product_unit_snapshot,product_name}',
      product_reference_id_snapshot = nullif(
        v_context #>> '{product_unit_snapshot,product_reference_id}',
        ''
      ),
      product_sku_snapshot = nullif(
        v_context #>> '{product_unit_snapshot,sku}',
        ''
      ),
      unit_name_snapshot =
        v_context #>> '{product_unit_snapshot,unit_name}',
      sellable_status_snapshot =
        v_context #>> '{product_unit_snapshot,sellable_status}',
      list_price_snapshot_minor = nullif(
        v_context #>> '{product_unit_snapshot,list_price_minor}',
        ''
      )::bigint,
      floor_price_snapshot_minor = nullif(
        v_context #>> '{product_unit_snapshot,floor_price_minor}',
        ''
      )::bigint,
      review_status = case
        when jsonb_array_length(
          v_context #> '{validation_outcome,warning_codes}'
        ) > 0 then 'warning'
        else 'clear'
      end,
      price_check_status = case
        when coalesce((v_context ->> 'is_below_floor')::boolean, false)
          then 'override_allowed'
        when not coalesce((v_context ->> 'has_floor_price')::boolean, false)
          then 'not_checked'
        else 'normal'
      end,
      warning_codes = v_context #> '{validation_outcome,warning_codes}',
      blocking_codes = '[]'::jsonb,
      disabled_at = null,
      disabled_by = null,
      disabled_reason = null,
      updated_by = v_actor_id,
      updated_at = statement_timestamp(),
      version = v_rule.version + 1
  where id = v_rule.id
  returning * into v_rule;

  insert into pricing.customer_price_rule_activities (
    tenant_id,
    customer_price_rule_id,
    activity_type,
    old_value,
    new_value,
    created_by
  ) values (
    p_tenant_id,
    v_rule.id,
    'reenabled',
    v_old_value,
    jsonb_build_object(
      'status', v_rule.status,
      'version', v_rule.version,
      'validation_outcome', v_context -> 'validation_outcome',
      'acknowledge_floor_warning', coalesce(p_acknowledge_floor_warning, false)
    ),
    v_actor_id
  );

  v_result := pricing._customer_price_rule_result(
    v_rule.id,
    coalesce((v_context ->> 'can_override_floor')::boolean, false)
  ) -> 'rule';

  return v_result || jsonb_build_object(
    'derived_status', case
      when v_rule.effective_from > p_business_date then 'not_yet_effective'
      else 'applying'
    end,
    'disabled_at', null,
    'disabled_by', null,
    'disabled_reason', null
  );
end;
$$;

