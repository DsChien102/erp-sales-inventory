create or replace function iam._unwind_provisioning_owner_membership(
  p_tenant_id uuid
)
returns void
language plpgsql
security definer
set search_path = iam, pg_temp
as $$
declare
  v_status text;
  v_membership_id uuid;
  v_now timestamptz := timezone('utc', now());
begin
  select coalesce(t.status, 'active') into v_status
  from iam.tenants t
  where t.id = p_tenant_id
  for update;

  if not found or v_status <> 'provisioning' then
    return;
  end if;

  select m.id into v_membership_id
  from iam.memberships m
  where m.tenant_id = p_tenant_id
    and m.is_owner is true
    and m.is_active
  order by m.created_at
  limit 1
  for update;

  if v_membership_id is null then
    return;
  end if;

  -- Bypass LAST_OWNER_PROTECTED: provisioning abort of designated owner only.
  update iam.memberships
  set
    is_owner = false,
    is_active = false,
    removed_at = v_now,
    status_changed_at = v_now,
    version = version + 1,
    updated_at = v_now
  where id = v_membership_id;
end;
$$;

