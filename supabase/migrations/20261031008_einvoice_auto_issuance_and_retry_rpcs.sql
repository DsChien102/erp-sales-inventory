      'NO_ACTIVE_PROVIDER_CONNECTION'::text as reason;
    return;
  end if;

  select ts.tenant_id
  into v_settings_tenant_id
  from einvoice.tenant_settings ts
  where ts.tenant_id = p_tenant_id
    and ts.default_template_id is not null
  limit 1;

  if v_settings_tenant_id is null then
    return query select
      false as started,
      false as skipped,
      v_proc.id as process_id,
      null::uuid as attempt_id,
      'PENDING_REEVALUATION'::text as status,
      'NO_ACTIVE_ISSUANCE_PROFILE'::text as reason;
    return;
  end if;

  -- KI-04: người mua phải đủ dữ liệu; thiếu thì giữ chờ, cập nhật mã chặn.
  v_buyer_blocker := einvoice._buyer_issuance_blocker(
    p_tenant_id, v_proc.sales_order_id, v_source.buyer_partner_id, v_source.buyer_snapshot
  );
  if v_buyer_blocker is not null then
    update einvoice.auto_issuance_processes
    set blocker_code = v_buyer_blocker,
        last_evaluated_at = now()
    where id = v_proc.id;

    return query select
      false as started,
      false as skipped,
      v_proc.id as process_id,
      null::uuid as attempt_id,
      'PENDING_REEVALUATION'::text as status,
      v_buyer_blocker::text as reason;
    return;
  end if;

  -- Ready: start attempt
  v_intent := jsonb_build_object(
    'operation', 'ISSUE_ORIGINAL',
    'sales_order_id', v_proc.sales_order_id,
    'source_version', v_proc.sales_order_version,
    'acknowledge_warnings', false
  );
  v_intent_hash := encode(
    digest(convert_to(v_intent::text, 'UTF8'), 'sha256'),
    'hex'
  );

  select *
  into v_start_res
  from einvoice._start_issuance_attempt(
