-- 4. einvoice.start_auto_issuance
create or replace function einvoice.start_auto_issuance(
  p_tenant_id uuid,
  p_sales_order_id uuid,
  p_trigger_key varchar(255),
  p_idempotency_key varchar(150)
) returns table(
  started boolean,
  skipped boolean,
  process_id uuid,
  attempt_id uuid,
  status text,
  reason text
) language plpgsql security definer set search_path = einvoice, extensions, public as $$
declare
  v_existing_proc einvoice.auto_issuance_processes%rowtype;
  v_policy einvoice.tenant_settings%rowtype;
  v_source record;
  v_source_version text;
  v_provider_connection_id uuid;
  v_settings_tenant_id uuid;
  v_buyer_blocker text;
  v_proc_id uuid;
  v_start_res record;
  v_intent jsonb;
  v_intent_hash text;
  v_existing_invoice uuid;
  v_active_attempt uuid;
begin
  if p_trigger_key is null or btrim(p_trigger_key) = '' then
    raise exception 'VALIDATION_ERROR: trigger_key is required';
  end if;
  if p_idempotency_key is null or btrim(p_idempotency_key) = '' then
    raise exception 'VALIDATION_ERROR: idempotency_key is required';
  end if;

  -- 1. Check duplicate trigger key (idempotent replay)
  select pr.*
  into v_existing_proc
  from einvoice.auto_issuance_processes pr
  where pr.tenant_id = p_tenant_id
    and pr.trigger_key = p_trigger_key
  for update;

  if found then
    return query select
      (v_existing_proc.status = 'ATTEMPT_STARTED')::boolean as started,
      (v_existing_proc.status = 'SKIPPED')::boolean as skipped,
      v_existing_proc.id as process_id,
      null::uuid as attempt_id,
      v_existing_proc.status as status,
      v_existing_proc.blocker_code as reason;
    return;
  end if;

  -- 1b. Một dòng / đơn. Sales phát sales_order_finalized.v1 một lần cho mỗi
  -- đơn; nhánh này là lưới an toàn khi có sự kiện thứ hai khác trigger_key.
  select pr.*
  into v_existing_proc
  from einvoice.auto_issuance_processes pr
  where pr.tenant_id = p_tenant_id
    and pr.sales_order_id = p_sales_order_id
  for update;

  if found then
    if v_existing_proc.status = 'PENDING_REEVALUATION' then
      return query
      select * from einvoice.reevaluate_auto_issuance(
        p_tenant_id, v_existing_proc.id, p_trigger_key
      );
      return;
    end if;
    return query select
      (v_existing_proc.status = 'ATTEMPT_STARTED')::boolean,
      (v_existing_proc.status = 'SKIPPED')::boolean,
      v_existing_proc.id,
      null::uuid,
      v_existing_proc.status,
      v_existing_proc.blocker_code;
    return;
  end if;

  -- 2. Check Automation Policy
  select ap.*
  into v_policy
  from einvoice.tenant_settings ap
  where ap.tenant_id = p_tenant_id;

  if not found or not coalesce(v_policy.auto_issue_enabled, false) then
    insert into einvoice.auto_issuance_processes (
      tenant_id,
      sales_order_id,
      sales_order_version,
      buyer_partner_id,
      trigger_key,
      provider_idempotency_key,
      status,
      blocker_code,
      last_evaluated_at
    ) values (
      p_tenant_id,
      p_sales_order_id,
      null,
      null,
      p_trigger_key,
      p_idempotency_key,
      'SKIPPED',
      'AUTOMATION_POLICY_DISABLED',
      now()
    )
    returning id into v_proc_id;

    return query select
      false as started,
      true as skipped,
      v_proc_id as process_id,
      null::uuid as attempt_id,
      'SKIPPED'::text as status,
      'AUTOMATION_POLICY_DISABLED'::text as reason;
    return;
  end if;

  -- 3. Check already issued or active attempt locks
  select ei.id
  into v_existing_invoice
  from einvoice.electronic_invoices ei
  where ei.tenant_id = p_tenant_id
    and ei.sales_order_id = p_sales_order_id;

  if found then
    insert into einvoice.auto_issuance_processes (
      tenant_id,
      sales_order_id,
      sales_order_version,
      buyer_partner_id,
      trigger_key,
      provider_idempotency_key,
      status,
      blocker_code,
      last_evaluated_at
    ) values (
      p_tenant_id,
      p_sales_order_id,
      null,
      null,
      p_trigger_key,
      p_idempotency_key,
      'SKIPPED',
      'ALREADY_ISSUED',
      now()
    )
    returning id into v_proc_id;

    return query select
      false as started,
      true as skipped,
      v_proc_id as process_id,
      null::uuid as attempt_id,
      'SKIPPED'::text as status,
      'ALREADY_ISSUED'::text as reason;
    return;
  end if;

  select ia.id
  into v_active_attempt
  from einvoice.invoice_issuances ii
  join einvoice.issuance_attempts ia on ia.invoice_issuance_id = ii.id
  where ii.tenant_id = p_tenant_id
    and ii.sales_order_id = p_sales_order_id
    and ia.status in ('PREPARING', 'SUBMITTED', 'WAITING_RESULT', 'RECONCILING')
  limit 1;

  if found then
    insert into einvoice.auto_issuance_processes (
      tenant_id,
      sales_order_id,
      sales_order_version,
      buyer_partner_id,
      trigger_key,
      provider_idempotency_key,
      status,
      blocker_code,
      last_evaluated_at
    ) values (
      p_tenant_id,
      p_sales_order_id,
      null,
      null,
      p_trigger_key,
      p_idempotency_key,
      'SKIPPED',
      'OPERATION_IN_PROGRESS',
      now()
    )
    returning id into v_proc_id;

    return query select
      false as started,
      true as skipped,
      v_proc_id as process_id,
      null::uuid as attempt_id,
      'SKIPPED'::text as status,
      'OPERATION_IN_PROGRESS'::text as reason;
    return;
  end if;

  -- 4. Load Source Snapshot & Readiness
  select s.*
  into v_source
  from einvoice.load_issuance_source_snapshot(p_tenant_id, p_sales_order_id) s;

  v_source_version := v_source.source_version;

  -- Đơn đã trả hết: không còn gì để xuất hóa đơn → SKIPPED (không chờ lại).
  if coalesce(v_source.blockers, '[]'::jsonb) ? 'ORDER_FULLY_RETURNED' then
    insert into einvoice.auto_issuance_processes (
      tenant_id,
      sales_order_id,
      sales_order_version,
      buyer_partner_id,
      trigger_key,
      provider_idempotency_key,
      status,
      blocker_code,
      last_evaluated_at
    ) values (
      p_tenant_id,
      p_sales_order_id,
      v_source.source_version,
      v_source.buyer_partner_id,
      p_trigger_key,
      p_idempotency_key,
      'SKIPPED',
      'ORDER_FULLY_RETURNED',
      now()
