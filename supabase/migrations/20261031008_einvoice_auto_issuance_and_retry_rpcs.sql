  end if;

  -- Load source snapshot
  select s.*
  into v_source
  from einvoice.load_issuance_source_snapshot(p_tenant_id, v_proc.sales_order_id) s;

  if coalesce(v_source.blockers, '[]'::jsonb) ? 'ORDER_FULLY_RETURNED' then
