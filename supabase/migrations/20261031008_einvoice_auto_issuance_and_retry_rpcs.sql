    p_trigger_key,
    p_idempotency_key,
    'ATTEMPT_STARTED',
    now()
  )
  returning id into v_proc_id;

  return query select
    true as started,
    false as skipped,
    v_proc_id as process_id,
    v_start_res.attempt_id as attempt_id,
    'ATTEMPT_STARTED'::text as status,
    null::text as reason;
end;
$$;

