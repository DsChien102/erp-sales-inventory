declare
  v_proc einvoice.auto_issuance_processes%rowtype;
  v_source record;
  v_provider_connection_id uuid;
  v_settings_tenant_id uuid;
  v_buyer_blocker text;
  v_intent jsonb;
  v_intent_hash text;
  v_start_res record;
