create or replace function catalog.suggest_product_unit_price(
  p_tenant_id uuid,
  p_product_id uuid,
  p_product_unit_id uuid default null
)
returns table (
  product_id uuid,
  product_unit_id uuid,
  unit_name text,
  base_price numeric,
  currency text,
  suggested_list_price numeric,
  suggested_floor_price numeric,
  store_price_rule_id uuid,
  store_price_rule_name text,
  base_price_version bigint,
  can_suggest boolean,
  unavailable_reason text
)
language plpgsql
security definer
set search_path = catalog, iam, pg_temp
as $$
declare
  v_unit_id uuid;
  v_unit_name text;
  v_base_price numeric;
  v_currency text;
  v_base_price_version bigint;
  v_rule catalog.store_price_rules%rowtype;
  v_prices record;
begin
  if auth.uid() is null then
    raise exception 'not authenticated';
  end if;

  if not iam.has_permission(p_tenant_id, 'catalog.product.manage_pricing') then
    raise exception 'permission denied: catalog.product.manage_pricing';
  end if;

  if not exists (
    select 1 from catalog.products
    where id = p_product_id and tenant_id = p_tenant_id and deleted_at is null
  ) then
    raise exception 'product not found';
  end if;

  v_unit_id := catalog._resolve_base_product_unit_id(p_tenant_id, p_product_id, p_product_unit_id);
  if v_unit_id is null then
    raise exception 'missing base unit';
  end if;

  select u.unit_name into v_unit_name
  from catalog.product_units u
  where u.id = v_unit_id;

  select bp.base_price_after_vat, bp.currency,
         floor(extract(epoch from bp.updated_at) * 1000)::bigint
  into v_base_price, v_currency, v_base_price_version
  from catalog.product_base_price_profiles bp
  where bp.product_id = p_product_id
    and bp.tenant_id = p_tenant_id;

  if v_base_price is null then
    return query select
      p_product_id,
      v_unit_id,
      v_unit_name,
      0::numeric,
      coalesce(v_currency, 'VND'),
      null::numeric,
      null::numeric,
      null::uuid,
      null::text,
      v_base_price_version,
      false,
      'Cần có Giá cơ sở định giá trước';
    return;
  end if;

  select * into v_rule
  from catalog.store_price_rules r
  where r.tenant_id = p_tenant_id
  limit 1;

  if v_rule.id is null then
    return query select
      p_product_id,
      v_unit_id,
      v_unit_name,
      v_base_price,
      coalesce(v_currency, 'VND'),
      null::numeric,
      null::numeric,
      null::uuid,
      null::text,
      v_base_price_version,
      false,
      'Tenant chưa có Store Price Rule';
    return;
  end if;

  if v_rule.status <> 'active' then
    return query select
      p_product_id,
      v_unit_id,
      v_unit_name,
      v_base_price,
      coalesce(v_currency, 'VND'),
      null::numeric,
      null::numeric,
      v_rule.id,
      v_rule.name,
      v_base_price_version,
      false,
      'Store Price Rule đang không hoạt động';
    return;
  end if;

  select * into v_prices
  from catalog._compute_suggested_prices(
    v_base_price,
    v_rule.list_markup_ratio,
    v_rule.floor_markup_ratio
  );

  return query select
    p_product_id,
    v_unit_id,
    v_unit_name,
    v_base_price,
    coalesce(v_currency, 'VND'),
    v_prices.suggested_list_price,
    v_prices.suggested_floor_price,
    v_rule.id,
    v_rule.name,
    v_base_price_version,
    true,
    null::text;
end;
$$;

