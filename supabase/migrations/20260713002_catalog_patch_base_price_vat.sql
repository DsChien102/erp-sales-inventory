create or replace function catalog.create_product(
  p_tenant_id uuid,
  p_name text,
  p_reference_id text,
  p_actor_id uuid default auth.uid(),
  p_trade_name text default null,
  p_sku text default null,
  p_barcode text default null,
  p_description text default null,
  p_note text default null,
  p_images jsonb default '[]'::jsonb,
  p_base_unit_name text default null,
  p_readiness_status text default 'incomplete',
  p_readiness_blockers jsonb default '[]'::jsonb,
  p_idempotency_key uuid default null
)
returns uuid
language plpgsql
security definer
set search_path = catalog, iam, pg_temp
as $$
declare
  v_product_id uuid;
  v_sku text;
  v_barcode text;
  v_reference_id text;
  v_base_unit_name text;
  v_image jsonb;
  v_readiness_status catalog.product_readiness_status;
  v_storage_key text;
  v_slot_id uuid;
begin
  if auth.uid() is null then
    raise exception 'not authenticated';
  end if;

  if p_actor_id is null or p_actor_id <> auth.uid() then
    raise exception 'actor mismatch';
  end if;

  if not iam.has_permission(p_tenant_id, 'catalog.product.create') then
    raise exception 'permission denied: catalog.product.create';
  end if;

  if length(btrim(coalesce(p_name, ''))) = 0 then
    raise exception 'product name is required';
  end if;

  v_reference_id := btrim(coalesce(p_reference_id, ''));
  if length(v_reference_id) = 0 then
    raise exception 'reference id is required';
  end if;

  if p_idempotency_key is not null then
    select p.id
    into v_product_id
    from catalog.products p
    where p.tenant_id = p_tenant_id
      and p.idempotency_key = p_idempotency_key;

    if v_product_id is not null then
      return v_product_id;
    end if;
  end if;

  v_sku := catalog._normalize_product_sku(p_sku);
  v_barcode := catalog._normalize_product_barcode(p_barcode);
  v_base_unit_name := nullif(btrim(coalesce(p_base_unit_name, '')), '');

  if exists (
    select 1
    from catalog.products p
    where p.tenant_id = p_tenant_id
      and p.reference_id = v_reference_id
  ) then
    raise exception 'duplicate reference_id';
  end if;

  if v_sku is not null
    and exists (
      select 1
      from catalog.products p
      where p.tenant_id = p_tenant_id
        and p.sku = v_sku
    ) then
    raise exception 'duplicate sku';
  end if;

  if v_barcode is not null
    and exists (
      select 1
      from catalog.products p
      where p.tenant_id = p_tenant_id
        and p.barcode = v_barcode
    ) then
    raise exception 'duplicate barcode';
  end if;

  v_readiness_status := coalesce(
    p_readiness_status::catalog.product_readiness_status,
    'incomplete'::catalog.product_readiness_status
  );

  begin
    insert into catalog.products (
      tenant_id,
      idempotency_key,
      reference_id,
      name,
      trade_name,
      sku,
      barcode,
      description,
      note,
      business_status,
      created_by,
      updated_by
    )
    values (
      p_tenant_id,
      p_idempotency_key,
      v_reference_id,
      btrim(p_name),
      nullif(btrim(coalesce(p_trade_name, '')), ''),
      v_sku,
      v_barcode,
      nullif(btrim(coalesce(p_description, '')), ''),
      nullif(btrim(coalesce(p_note, '')), ''),
      'active',
      p_actor_id,
      p_actor_id
    )
    returning id into v_product_id;
  exception
    when unique_violation then
      if exists (
        select 1 from catalog.products p
        where p.tenant_id = p_tenant_id
          and p.reference_id = v_reference_id
      ) then
        raise exception 'duplicate reference_id';
      end if;
      if v_sku is not null
        and exists (
          select 1 from catalog.products p
          where p.tenant_id = p_tenant_id and p.sku = v_sku
        ) then
        raise exception 'duplicate sku';
      end if;
      if v_barcode is not null
        and exists (
          select 1 from catalog.products p
          where p.tenant_id = p_tenant_id and p.barcode = v_barcode
        ) then
        raise exception 'duplicate barcode';
      end if;
      raise;
  end;

  insert into catalog.product_base_price_profiles (
    product_id,
    tenant_id,
    mode,
    base_price_after_vat,
    base_price_before_vat,
    currency
  )
  values (v_product_id, p_tenant_id, 'manual', null, null, 'VND')
  on conflict (product_id) do nothing;

  if p_images is not null and jsonb_typeof(p_images) = 'array' then
    for v_image in select * from jsonb_array_elements(p_images)
    loop
      v_storage_key := btrim(v_image ->> 'storage_key');
      if v_storage_key is null or length(v_storage_key) = 0 then
        continue;
      end if;

      begin
        v_slot_id := catalog._consume_image_upload_slot(
          p_tenant_id,
          v_storage_key,
          p_actor_id
        );
      exception
        when others then
          continue;
      end;

      insert into catalog.product_images (
        tenant_id,
        product_id,
        storage_key,
        file_url,
        is_primary,
        sort_order,
        processing_status,
        upload_slot_id
      )
      values (
        p_tenant_id,
        v_product_id,
        v_storage_key,
        nullif(btrim(coalesce(v_image ->> 'url', '')), ''),
        coalesce((v_image ->> 'is_primary')::boolean, false),
        coalesce((v_image ->> 'sort_order')::integer, 0),
        'ready',
        v_slot_id
      );
    end loop;
  end if;

  if v_base_unit_name is not null then
    insert into catalog.product_units (
      tenant_id,
      product_id,
      unit_name,
      is_base_unit,
      conversion_rate_to_base
    )
    values (
      p_tenant_id,
      v_product_id,
      v_base_unit_name,
      true,
      1
    );
  end if;

  insert into catalog.product_readiness (
    product_id,
    tenant_id,
    status,
    blockers
  )
  values (
    v_product_id,
    p_tenant_id,
    v_readiness_status,
    coalesce(p_readiness_blockers, '[]'::jsonb)
  );

  insert into catalog.product_change_history (
    tenant_id,
    product_id,
    action,
    payload,
    actor_id
  )
  values (
    p_tenant_id,
    v_product_id,
    'CREATED',
    jsonb_build_object(
      'product_id', v_product_id,
      'reference_id', v_reference_id,
      'name', btrim(p_name),
      'sku', v_sku,
      'barcode', v_barcode
    ),
    p_actor_id
  );

  return v_product_id;
end;
$$;

