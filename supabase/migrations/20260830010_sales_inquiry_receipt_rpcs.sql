-- As-sold receipt for the «Đơn gốc» tab: original order lines, sale totals
-- and checkout collections only. Read-only and never persisted — the stored
-- receipt (generate_sales_receipt) is the after-return/exchange version.
create or replace function sales.get_sales_order_original_receipt(
  p_query_id uuid,
  p_tenant_id uuid,
  p_actor_id uuid,
  p_sales_order_id uuid
) returns jsonb
language plpgsql
security definer
set search_path = sales, iam, public, pg_temp
as $$
declare
  v_order sales.sales_orders%rowtype;
  v_payments jsonb;
  v_paid_minor bigint;
begin
  if auth.uid() is distinct from p_actor_id then
    raise exception using message = jsonb_build_object(
      'code', 'PERMISSION_DENIED', 'message', 'Permission denied.'
    )::text;
  end if;
  if iam.has_permission(p_tenant_id, 'sales.receipt.view') is not true then
    raise exception using message = jsonb_build_object(
      'code', 'PERMISSION_DENIED', 'message', 'Permission denied.'
    )::text;
  end if;

  select * into v_order from sales.sales_orders
  where id = p_sales_order_id and tenant_id = p_tenant_id;
  if not found then
    raise exception using message = jsonb_build_object(
      'code', 'NOT_FOUND', 'message', 'Sales order not found.'
    )::text;
  end if;
  if not iam.can_access_store(p_tenant_id, v_order.store_id, p_actor_id) then
    raise exception using message = jsonb_build_object(
      'code', 'DATA_SCOPE_DENIED', 'message', 'Store scope denied.'
    )::text;
  end if;

  perform sales._assert_sales_actor(
    p_tenant_id, p_actor_id, v_order.store_id, 'sales.receipt.view'
  );

  -- Checkout collections only: later collections/refunds belong to the
  -- after-return/exchange receipt.
  select
    coalesce(jsonb_agg(jsonb_build_object(
      'method', method_total.payment_method_code,
      'amount', jsonb_build_object(
        'amountMinor', method_total.paid_minor,
        'currencyCode', v_order.currency_code
      ),
      'status', 'confirmed'
    ) order by method_total.first_at, method_total.payment_method_code), '[]'::jsonb),
    coalesce(sum(method_total.paid_minor), 0)::bigint
  into v_payments, v_paid_minor
  from (
    select
      transaction.payment_method_code,
      sum(transaction.amount_minor) as paid_minor,
      min(transaction.occurred_at) as first_at
    from sales.sales_payment_transactions transaction
    join sales.sales_order_settlements settlement
      on settlement.id = transaction.sales_order_settlement_id
     and settlement.tenant_id = transaction.tenant_id
    where transaction.tenant_id = p_tenant_id
      and settlement.sales_order_id = p_sales_order_id
      and transaction.status = 'confirmed'
      and transaction.source_context = 'checkout'
      and transaction.transaction_type = 'collection'
    group by transaction.payment_method_code
  ) method_total;

  return jsonb_build_object(
    'receiptNumber', 'PBH-' || to_char(v_order.created_at at time zone 'utc', 'YYYYMMDD')
      || '-' || upper(substr(replace(v_order.id::text, '-', ''), 1, 8)),
    'orderNumber', coalesce(
      nullif(btrim(v_order.order_code), ''),
      'SO-' || upper(substr(replace(v_order.id::text, '-', ''), 1, 12))
    ),
    'soldAt', to_char(v_order.completed_at at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    'store', coalesce(v_order.sales_context_snapshot -> 'store', '{}'::jsonb),
    'seller', coalesce(v_order.sales_context_snapshot -> 'seller', '{}'::jsonb),
    'customer', v_order.sales_context_snapshot -> 'customer',
    'lines', sales._sales_order_lines_payload(p_tenant_id, p_sales_order_id, v_order.currency_code),
    'subtotal', jsonb_build_object(
      'amountMinor', v_order.subtotal_amount_minor,
      'currencyCode', v_order.currency_code
    ),
    'discountTotal', jsonb_build_object(
      'amountMinor', coalesce(v_order.discount_amount_minor, 0),
      'currencyCode', v_order.currency_code
    ),
    'taxTotal', jsonb_build_object(
      'amountMinor', coalesce(v_order.tax_amount_minor, 0),
      'currencyCode', v_order.currency_code
    ),
    'roundingTotal', jsonb_build_object(
      'amountMinor', coalesce(v_order.rounding_amount_minor, 0),
      'currencyCode', v_order.currency_code
    ),
    'orderTotal', jsonb_build_object(
      'amountMinor', v_order.payable_amount_minor,
      'currencyCode', v_order.currency_code
    ),
    'paidTotal', jsonb_build_object(
      'amountMinor', v_paid_minor,
      'currencyCode', v_order.currency_code
    ),
    'outstandingTotal', jsonb_build_object(
      'amountMinor', greatest(v_order.payable_amount_minor - v_paid_minor, 0),
      'currencyCode', v_order.currency_code
    ),
    'payments', v_payments,
    'dueAt', case
      when v_order.payment_due_date is null then null
      else to_char(v_order.payment_due_date, 'YYYY-MM-DD')
    end
  );
end;
$$;

create or replace function sales.record_sales_receipt_activity(
  p_command_id uuid,
  p_tenant_id uuid,
  p_actor_id uuid,
  p_receipt_id uuid,
  p_activity_type text,
  p_idempotency_key text,
  p_payload_hash text,
  p_correlation_id text,
  p_causation_id text default null,
  p_expected_source_version integer default null
) returns jsonb
language plpgsql
security definer
set search_path = sales, iam, public, pg_temp
as $$
declare
  v_receipt sales.sales_receipts%rowtype;
  v_order sales.sales_orders%rowtype;
  v_permission text;
  v_idem jsonb;
  v_correlation uuid;
  v_result jsonb;
  v_snapshot jsonb;
  v_hash text;
begin
  begin
    v_correlation := nullif(trim(coalesce(p_correlation_id, '')), '')::uuid;
  exception when others then
    raise exception using message = jsonb_build_object(
      'code', 'CONTEXT_INVALID', 'message', 'Correlation id is invalid.'
    )::text;
  end;
  if v_correlation is null then
    v_correlation := p_command_id;
  end if;

  if p_activity_type not in ('printed', 'shared', 'archived') then
    raise exception using message = jsonb_build_object(
      'code', 'CONTEXT_INVALID', 'message', 'Receipt activity is invalid.'
    )::text;
  end if;

  v_permission := case p_activity_type
    when 'printed' then 'sales.receipt.print'
    when 'shared' then 'sales.receipt.share'
    when 'archived' then 'sales.receipt.archive'
  end;

  select * into v_receipt from sales.sales_receipts
  where id = p_receipt_id and tenant_id = p_tenant_id
  for update;
  if not found then
    raise exception using message = jsonb_build_object(
      'code', 'NOT_FOUND', 'message', 'Sales receipt not found.'
    )::text;
  end if;

  select * into v_order from sales.sales_orders
  where id = v_receipt.sales_order_id and tenant_id = p_tenant_id
  for update;
  if not found or not iam.can_access_store(p_tenant_id, v_order.store_id, p_actor_id) then
    raise exception using message = jsonb_build_object(
      'code', 'DATA_SCOPE_DENIED', 'message', 'Store scope denied.'
    )::text;
  end if;

  perform sales._assert_sales_actor(
    p_tenant_id, p_actor_id, v_order.store_id, v_permission
  );

  if p_expected_source_version is not null
     and v_order.version <> p_expected_source_version then
    raise exception using message = jsonb_build_object(
      'code', 'STALE_VERSION', 'message', 'Receipt source version is stale.'
    )::text;
  end if;

  v_idem := sales._begin_sales_idempotency(
    p_tenant_id,
    'record_sales_receipt_activity:' || p_activity_type,
    p_idempotency_key,
    p_payload_hash);
  if v_idem ->> 'decision' = 'replay' then
    return coalesce(v_idem -> 'result_snapshot', '{}'::jsonb);
  end if;
  if v_idem ->> 'decision' = 'in_progress' then
    raise exception using message = jsonb_build_object(
      'code', 'IN_PROGRESS', 'message', 'Receipt activity is already in progress.'
    )::text;
  end if;

  v_snapshot := v_receipt.receipt_snapshot;
  v_hash := v_receipt.content_hash;

  if p_activity_type in ('printed', 'shared') and v_receipt.status is distinct from 'generated' then
    raise exception using message = jsonb_build_object(
      'code', 'CONTEXT_INVALID',
      'message', 'Only a generated receipt can record print or share activity.'
    )::text;
  end if;

  if p_activity_type = 'archived' and v_receipt.status = 'archived' then
    v_result := sales._sales_receipt_envelope(v_receipt);
    perform sales._complete_sales_idempotency(
      p_tenant_id,
      'record_sales_receipt_activity:' || p_activity_type,
      trim(p_idempotency_key),
      'succeeded',
      v_result);
    return v_result;
  end if;

  insert into sales.sales_receipt_activities (
    id, tenant_id, sales_receipt_id, actor_user_id, activity_type, occurred_at
  ) values (
    gen_random_uuid(), p_tenant_id, v_receipt.id, p_actor_id, p_activity_type, now()
  );

  if p_activity_type = 'archived' then
    update sales.sales_receipts
    set status = 'archived'
    where id = v_receipt.id
      and tenant_id = p_tenant_id
      and receipt_snapshot = v_snapshot
      and content_hash = v_hash
    returning * into v_receipt;
  end if;

  if v_receipt.receipt_snapshot is distinct from v_snapshot
     or v_receipt.content_hash is distinct from v_hash then
    raise exception using message = jsonb_build_object(
      'code', 'CONTEXT_INVALID',
      'message', 'Receipt activity must not change the stored snapshot.'
    )::text;
  end if;

  v_result := sales._sales_receipt_envelope(v_receipt);
  perform sales._complete_sales_idempotency(
    p_tenant_id,
    'record_sales_receipt_activity:' || p_activity_type,
    trim(p_idempotency_key),
    'succeeded',
    v_result);
  return v_result;
end;
$$;


