  line_id uuid,
  line_kind text,
  product_id uuid,
  product_unit_id uuid,
  product_snapshot jsonb,
  product_unit_snapshot jsonb,
  unit_price_minor bigint,
  quantity_micros bigint,
  gross_minor bigint,
  discount_minor bigint,
  line_total_minor bigint,
  note text,
  sort_group integer,
  sort_at timestamptz,
  sort_seq integer
)
language sql
stable
security definer
set search_path = sales, iam, public, pg_temp
as $$
  select
    unit.line_id,
    unit.line_kind,
    unit.product_id,
    unit.product_unit_id,
    unit.product_snapshot,
    unit.product_unit_snapshot,
    unit.unit_price_minor,
    unit.remaining_micros,
    unit.line_total_minor + unit.discount_minor,
    unit.discount_minor,
    unit.line_total_minor,
    unit.note,
    unit.sort_group,
    unit.sort_at,
    unit.sort_seq
  from (
    select
      src.*,
      round(src.full_discount_minor::numeric * src.remaining_micros / src.sold_micros)::bigint
        as discount_minor,
      round(src.full_line_total_minor::numeric * src.remaining_micros / src.sold_micros)::bigint
        as line_total_minor
    from (
      -- Original sales order lines net of returned quantity.
      select
        l.id as line_id,
        'original'::text as line_kind,
        l.product_id,
        l.product_unit_id,
        l.product_snapshot,
        l.product_unit_snapshot,
        l.unit_price_minor,
        l.quantity_micros as sold_micros,
        l.discount_amount_minor as full_discount_minor,
        l.line_total_minor as full_line_total_minor,
        l.line_note as note,
        l.quantity_micros - coalesce((
          select sum(rl.quantity_micros)
          from sales.return_exchange_lines rl
          join sales.return_exchange_orders r
            on r.id = rl.return_exchange_order_id and r.tenant_id = rl.tenant_id
          where r.tenant_id = p_tenant_id
            and r.sales_order_id = p_sales_order_id
            and r.status in ('confirmed', 'processing', 'completed')
            and rl.line_role = 'returned'
            and rl.original_sales_order_line_id = l.id
        ), 0) as remaining_micros,
        0 as sort_group,
        null::timestamptz as sort_at,
        l.line_sequence as sort_seq
      from sales.sales_order_lines l
      where l.tenant_id = p_tenant_id
        and l.sales_order_id = p_sales_order_id

      union all

      -- Exchange lines (new goods) net of their own later returns.
      select
        xl.id,
        'exchange'::text,
        xl.product_id,
        xl.product_unit_id,
        xl.product_snapshot,
        xl.product_unit_snapshot,
        xl.unit_value_minor,
        xl.quantity_micros,
        0::bigint,
        round(xl.unit_value_minor::numeric * xl.quantity_micros / 1000000)::bigint,
        null::text,
        xl.quantity_micros - coalesce((
          select sum(rl.quantity_micros)
          from sales.return_exchange_lines rl
          join sales.return_exchange_orders r
            on r.id = rl.return_exchange_order_id and r.tenant_id = rl.tenant_id
          where r.tenant_id = p_tenant_id
            and r.sales_order_id = p_sales_order_id
            and r.status in ('confirmed', 'processing', 'completed')
            and rl.line_role = 'returned'
            and rl.source_exchange_line_id = xl.id
        ), 0),
        1,
        xr.created_at,
        xl.line_sequence
      from sales.return_exchange_lines xl
      join sales.return_exchange_orders xr
        on xr.id = xl.return_exchange_order_id and xr.tenant_id = xl.tenant_id
      where xl.tenant_id = p_tenant_id
        and xr.sales_order_id = p_sales_order_id
        and xr.status in ('confirmed', 'processing', 'completed')
        and xl.line_role = 'exchange'
    ) src
  ) unit
  where unit.remaining_micros > 0;
$$;

