  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(
      p_tenant_id::text || ':rule:' || p_customer_id::text || ':'
        || p_product_id::text || ':' || p_product_unit_id::text,
      0
    )
  );

  perform pricing._auto_disable_overlapping_customer_price_rules(
    p_tenant_id,
    p_rule_id,
    p_customer_id,
    p_product_id,
    p_product_unit_id,
    p_effective_from,
    p_effective_to,
    v_actor_id,
    'created'
  );

  insert into pricing.customer_price_rules (
    id,
    tenant_id,
    customer_id,
    product_id,
    product_unit_id,
    customer_display_name_snapshot,
    customer_status_snapshot,
    product_name_snapshot,
    product_reference_id_snapshot,
    product_sku_snapshot,
    unit_name_snapshot,
    sellable_status_snapshot,
    rule_price_minor,
    currency_code,
    review_status,
    effective_from,
    effective_to,
    list_price_snapshot_minor,
    floor_price_snapshot_minor,
    price_check_status,
    warning_codes,
    note,
    created_by,
    updated_by,
    idempotency_key,
    payload_hash
  ) values (
    p_rule_id,
    p_tenant_id,
    p_customer_id,
    p_product_id,
