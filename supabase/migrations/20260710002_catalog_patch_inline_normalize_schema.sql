create or replace function catalog._normalize_product_sku(p_sku text)
returns text
language sql
immutable
as $$
  select nullif(lower(btrim(coalesce(p_sku, ''))), '');
$$;

create or replace function catalog._normalize_product_barcode(p_barcode text)
