final class SearchKeywordNormalizer {
  const SearchKeywordNormalizer._();

  static String? normalizeKeyword(String? keyword) {
    if (keyword == null) {
      return null;
    }
    final value = keyword.trim();
    return value.isEmpty ? null : value;
  }

  /// Lowercase + strip Vietnamese diacritics (approximate Postgres `unaccent`).
  static String foldForSearch(String value) {
    final lower = value.toLowerCase();
    final buffer = StringBuffer();
    for (final codeUnit in lower.codeUnits) {
      buffer.writeCharCode(_foldCodeUnit(codeUnit));
    }
    return buffer.toString();
  }

  static int _foldCodeUnit(int codeUnit) {
    // Vietnamese + Latin diacritic ranges commonly used in product names.
    const map = <int, int>{
      0x00E0: 0x61, // à
      0x00E1: 0x61, // á
      0x00E2: 0x61, // â
      0x00E3: 0x61, // ã
      0x00E8: 0x65, // è
      0x00E9: 0x65, // é
      0x00EA: 0x65, // ê
      0x00EC: 0x69, // ì
      0x00ED: 0x69, // í
      0x00F2: 0x6F, // ò
      0x00F3: 0x6F, // ó
      0x00F4: 0x6F, // ô
      0x00F5: 0x6F, // õ
      0x00F9: 0x75, // ù
      0x00FA: 0x75, // ú
      0x00FD: 0x79, // ý
      0x0111: 0x64, // đ
      0x0103: 0x61, // ă
      0x01A1: 0x6F, // ơ
      0x01B0: 0x75, // ư
      0x1EA1: 0x61, // ạ
      0x1EA3: 0x61, // ả
      0x1EA5: 0x61, // ấ
      0x1EA7: 0x61, // ầ
      0x1EA9: 0x61, // ẩ
      0x1EAB: 0x61, // ẫ
      0x1EAD: 0x61, // ậ
      0x1EAF: 0x61, // ắ
      0x1EB1: 0x61, // ằ
      0x1EB3: 0x61, // ẳ
      0x1EB5: 0x61, // ẵ
      0x1EB7: 0x61, // ặ
      0x1EB9: 0x65, // ẹ
      0x1EBB: 0x65, // ẻ
      0x1EBD: 0x65, // ẽ
      0x1EBF: 0x65, // ế
      0x1EC1: 0x65, // ề
      0x1EC3: 0x65, // ể
      0x1EC5: 0x65, // ễ
      0x1EC7: 0x65, // ệ
      0x1EC9: 0x69, // ỉ
      0x1ECB: 0x69, // ị
      0x1ECD: 0x6F, // ọ
      0x1ECF: 0x6F, // ỏ
      0x1ED1: 0x6F, // ố
      0x1ED3: 0x6F, // ồ
      0x1ED5: 0x6F, // ổ
      0x1ED7: 0x6F, // ỗ
      0x1ED9: 0x6F, // ộ
      0x1EDB: 0x6F, // ớ
      0x1EDD: 0x6F, // ờ
      0x1EDF: 0x6F, // ở
      0x1EE1: 0x6F, // ỡ
      0x1EE3: 0x6F, // ợ
      0x1EE5: 0x75, // ụ
      0x1EE7: 0x75, // ủ
      0x1EE9: 0x75, // ứ
      0x1EEB: 0x75, // ừ
      0x1EED: 0x75, // ử
      0x1EEF: 0x75, // ữ
      0x1EF1: 0x75, // ự
      0x1EF3: 0x79, // ỳ
      0x1EF5: 0x79, // ỵ
      0x1EF7: 0x79, // ỷ
      0x1EF9: 0x79, // ỹ
    };
    return map[codeUnit] ?? codeUnit;
  }
}
